// ---- A sweep over weight mixes: the model, the invariants and determinism.
let sweep = 0;
for (let a = 0; a <= 9; a += 1) {
  for (let b = 0; b <= 9; b += 1) {
    for (let c = 0; c <= 3; c += 1) {
      const weights = [a, b, c];
      if (weights.reduce((x, y) => x + y, 0) === 0) continue;
      const servers = weights.map((weight, index) => srv('s' + index, '10.0.0.' + (index + 1), '80', String(weight)));
      const result = C.analyze(plan({ backends: [backend('web', servers)] }));
      checkShares(result);
      const again = C.analyze(plan({ backends: [backend('web', servers)] }));
      assert.equal(again.config, result.config, 'the same plan gives the same file');
      sweep += 1;
    }
  }
}
assert.ok(sweep > 200, 'the sweep covers a few hundred weight mixes');

