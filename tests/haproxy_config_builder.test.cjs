// ---- Independent model. Each weight claims weight/total of the traffic, so a
// share must round to the nearest tenth of that fraction and the per-1,000
// counts must be the floor of the exact claim or one above it, must be handed
// to the servers with the largest remainders first, and must total 1,000.
function model(servers) {
  const total = servers.reduce((sum, server) => sum + Number(server.weight), 0);
  assert.ok(total > 0, 'model needs a positive weight total');
  const claims = servers.map((server) => {
    const weight = Number(server.weight);
    return { weight, exact: weight * 1000 / total, floor: Math.floor(weight * 1000 / total),
      tenths: Math.round(weight * 1000 / total) };
  });
  const assigned = claims.map((claim) => claim.floor);
  let left = 1000 - assigned.reduce((a, b) => a + b, 0);
  const order = claims.map((claim, index) => ({ index, rest: claim.weight * 1000 - claim.floor * total }))
    .sort((a, b) => b.rest - a.rest || a.index - b.index);
  for (let i = 0; i < left; i += 1) assigned[order[i].index] += 1;
  return claims.map((claim, index) => ({ tenths: claim.tenths, floor: claim.floor, count: assigned[index] }));
}
function checkShares(result) {
  for (const backend of result.backends) {
    const expected = model(backend.servers);
    const counts = backend.servers.map((server) => server.per1000);
    assert.equal(counts.reduce((a, b) => a + b, 0), 1000, backend.name + ' per-1,000 total');
    backend.servers.forEach((server, index) => {
      const claim = expected[index];
      assert.equal(Math.round(server.share * 10), claim.tenths, backend.name + ' / ' + server.name + ' share');
      assert.ok(server.per1000 === claim.floor || server.per1000 === claim.floor + 1,
        backend.name + ' / ' + server.name + ' per-1,000 is the floor or one above');
      assert.ok(Math.abs(server.per1000 - server.weight * 1000 / backend.weightTotal) <= 1,
        backend.name + ' / ' + server.name + ' within one of the exact claim');
    });
    assert.deepEqual(counts, expected.map((claim) => claim.count), backend.name + ' largest remainders');
  }
}

// ---- The emitted file: block order, one ACL per rule, the documented server
// option order, and no line that mentions a backend that does not exist.
function checkConfig(result) {
  const lines = result.config.split('\n');
  assert.equal(lines.pop(), '', 'the config ends with a newline');
  const text = lines.join('\n');
  assert.ok(text.startsWith('# Generated by virt.tools'), 'the header marks generated text');
  assert.ok(lines.includes('defaults') && lines.includes('frontend fe_main'), 'defaults and frontend');
  const bind = lines.find((line) => line.trim().startsWith('bind '));
  assert.equal(bind.trim(), 'bind ' + result.bind, 'the bind line matches the plan');
  const modeLine = lines[lines.indexOf('defaults') + 1];
  assert.equal(modeLine.trim(), 'mode ' + result.mode, 'mode follows defaults');

  const backendNames = result.backends.map((backend) => backend.name);
  const aclLines = lines.filter((line) => line.trim().startsWith('acl '));
  assert.equal(aclLines.length, result.rules.length, 'one ACL per rule');
  const aclNames = aclLines.map((line) => line.trim().split(/\s+/)[1]);
  assert.equal(new Set(aclNames).size, aclNames.length, 'ACL names are unique');
  const useLines = lines.filter((line) => line.trim().startsWith('use_backend '));
  assert.equal(useLines.length, result.rules.length, 'one use_backend per rule');
  useLines.forEach((line, index) => {
    const [, target, , acl] = line.trim().split(/\s+/);
    assert.equal(target, result.rules[index].backend, 'use_backend order follows the rules');
    assert.equal(acl, result.rules[index].acl, 'use_backend names its own ACL');
    assert.ok(backendNames.includes(target), 'use_backend targets a declared backend');
  });
  const defaultLine = lines.find((line) => line.trim().startsWith('default_backend '));
  assert.equal(defaultLine.trim(), 'default_backend ' + result.defaultBackend, 'default_backend is the first backend');
  assert.equal(result.defaultBackend, backendNames[0], 'first backend is the default');

  const blocks = backendNames.map((name) => {
    const at = lines.indexOf('backend ' + name);
    assert.ok(at > -1, 'backend block for ' + name);
    const body = [];
    for (let i = at + 1; i < lines.length && !lines[i].startsWith('backend ') && lines[i] !== ''; i += 1) body.push(lines[i]);
    return { name, body };
  });
  blocks.forEach((block, index) => {
    const target = result.backends[index];
    assert.equal(block.body[0].trim(), 'balance ' + (target.balance === 'hdr' ? 'hdr(' + target.hdr + ')' : target.balance),
      'balance line for ' + block.name);
    const servers = block.body.slice(1);
    assert.equal(servers.length, target.servers.length, 'server line count for ' + block.name);
    servers.forEach((line, position) => {
      const server = target.servers[position];
      const parts = line.trim().split(/\s+/);
      assert.deepEqual(parts.slice(0, 5), ['server', server.name, server.address + ':' + server.port, 'weight', String(server.weight)],
        'server line start for ' + server.name);
      const rest = parts.slice(5);
      const expectedRest = server.maxconn !== null ? ['maxconn', String(server.maxconn)] : [];
      assert.deepEqual(rest.slice(0, expectedRest.length), expectedRest, 'server options for ' + server.name);
      const tail = rest.slice(expectedRest.length);
      if (server.check) {
        assert.match(tail.join(' '), /^check inter [0-9]+ms fall [0-9]+ rise [0-9]+$/, 'check options for ' + server.name);
      } else {
        assert.deepEqual(tail, [], 'an unchecked server has no check options');
      }
    });
  });
  assert.ok(!/backend\s*$/.test(text), 'no empty backend header');
  return { lines, blocks };
}

