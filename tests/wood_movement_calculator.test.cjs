/* Wood movement: the Wood Handbook linear shrinkage relation, the species
   shrinkage table, a fixture generated by an independent Python reference, the
   catalog cases, unit equivalence and the page contract. The page core is never
   compared with itself: every expected number comes from the Python reference in
   runtime/maintenance or from the catalog record. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'wood-movement-calculator';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* wood-movement-core:start */';
const endMarker = '/* wood-movement-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const coreSource = html.slice(start, end + endMarker.length);
assert.ok(!/document\.|window\./.test(coreSource), 'the core stays free of DOM access');
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreSource + '\nmodule.exports = WoodMovementCore;', sandbox);
const C = sandbox.module.exports;

const near = (actual, expected, label, tolerance) => {
  const limit = tolerance === undefined ? 1e-9 : tolerance;
  assert.ok(Math.abs(actual - expected) <= limit,
    label + ': ' + actual + ' is not within ' + limit + ' of ' + expected);
};
const failure = (input) => {
  try { C.run(input); } catch (error) { return error.message; }
  return null;
};

// ---- Constants and the transcribed shrinkage table.
assert.equal(C.MM_PER_INCH, 25.4);
assert.equal(C.FSP, 30);
assert.equal(C.MIN_WIDTH_MM, 1);
assert.equal(C.MAX_WIDTH_MM, 12700);
assert.equal(C.MIN_MC, 0);
assert.equal(C.MAX_MC, 30);
assert.equal(C.SPECIES.length, 27, 'species count');
assert.equal(new Set(C.SPECIES.map((species) => species.id)).size, 27, 'duplicate species ids');
assert.equal(new Set(C.SPECIES.map((species) => species.name)).size, 27, 'duplicate species names');
for (const species of C.SPECIES) {
  assert.ok(species.radial > 0 && species.radial < species.tangential,
    species.id + ' must shrink less radially than tangentially');
}
// Spot checks against Wood Handbook Table 4-3 (green to ovendry, percent).
const table = {
  'oak-northern-red': [4.0, 8.6],
  'oak-white': [5.6, 10.5],
  'maple-sugar': [4.8, 9.9],
  'walnut-black': [5.5, 7.8],
  'cherry': [3.7, 7.1],
  'beech': [5.5, 11.9],
  'hickory-shagbark': [7.0, 10.5],
  'pine-eastern-white': [2.1, 6.1],
  'cedar-western-red': [2.4, 5.0],
  'douglas-fir-coast': [4.8, 7.6],
  'spruce-sitka': [4.3, 7.5],
  'birch-yellow': [7.3, 9.5]
};
for (const [id, [radial, tangential]] of Object.entries(table)) {
  const species = C.findSpecies(id);
  assert.ok(species, 'missing species ' + id);
  assert.equal(species.radial, radial, id + ' radial');
  assert.equal(species.tangential, tangential, id + ' tangential');
}
assert.equal(C.findSpecies('ebony'), null);
assert.equal(C.shrinkageAt(8.6, 30), 0);
near(C.shrinkageAt(8.6, 0), 8.6, 'shrinkage at oven-dry equals the total');
near(C.shrinkageAt(8.6, 15), 4.3, 'shrinkage is linear in moisture below the fiber saturation point');

// ---- The independent Python fixture: 58 boards, both units, both grains.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/wood_movement_vectors.json'), 'utf8'));
assert.ok(fixture.vectors.length >= 50, 'fixture size');
assert.equal(fixture.fsp, 30);
for (const vector of fixture.vectors) {
  const label = vector.name;
  const result = C.run(vector.input);
  for (const field of ['change', 'laterWidth', 'greenWidth', 'perPoint', 'changeAsPercent',
    'flatChange', 'quarterChange', 'total']) {
    near(result[field], vector.expected[field], label + ' ' + field, 1e-9);
  }
  assert.equal(result.species, vector.input.species, label + ' species');
  assert.equal(result.grain, vector.input.grain, label + ' grain');
}

// ---- The catalog cases, replayed through the documented input shape.
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const matches = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(matches.length, 1, 'slug must exist exactly once');
const entry = matches[0];
assert.equal(entry.name, 'Wood Movement Calculator');
assert.equal(entry.category, 'Crafts & Hobbies');
assert.equal(entry.subcategory, 'Estimation & Calculation');
assert.equal(entry.risk, 'low');
assert.equal(entry.maturity, 'draft');
assert.equal(entry.reviewedAt, null);
assert.equal(entry.listed, true);
assert.equal(entry.legacyCategory, null);
assert.equal(entry.icon, '\u{1FAB5}');
assert.equal(new Set(entry.tags).size, entry.tags.length, 'duplicate tags');
assert.equal(new Set(entry.aliases).size, entry.aliases.length, 'duplicate aliases');
assert.ok(entry.method.length > 800, 'method must document the formula, the table and the limits');
assert.equal(entry.sources.length, 1);
assert.equal(entry.sources[0].url, 'https://research.fs.usda.gov/download/treesearch/62243.pdf');
assert.ok(entry.sources[0].title.includes('Table 4'), 'source title names the shrinkage table');
assert.equal(entry.testCases.length, 20, 'catalog case count');
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'golden').length, 7);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'boundary').length, 3);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'validation').length, 10);

for (const testCase of entry.testCases) {
  if (testCase.kind === 'validation') {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.run(testCase.input);
  for (const [field, expected] of Object.entries(testCase.expected)) {
    near(result[field], expected, testCase.name + ' ' + field, 1e-9);
  }
}

// ---- Identities that follow from the relation itself.
const saturated = C.run({ width: '10', widthUnit: 'in', species: 'oak-white', grain: 'flat',
  mcNow: '30', mcLater: '10' });
near(saturated.greenWidth, 10, 'at fibre saturation the measured width is the green width');
near(saturated.change, saturated.laterWidth - 10, 'change is the later width less the measured width');
assert.ok(saturated.change < 0, 'drying from fibre saturation shrinks the board');

const dry = C.run({ width: '10', widthUnit: 'in', species: 'oak-white', grain: 'quarter',
  mcNow: '30', mcLater: '0' });
near(dry.laterWidth, 10 * (1 - 5.6 / 100), 'oven-dry width is the green width less the total radial shrinkage');
near(dry.change, -10 * 5.6 / 100, 'the movement is the total radial shrinkage of the green width');
const rewet = C.run({ width: '10', widthUnit: 'in', species: 'oak-white', grain: 'quarter',
  mcNow: '0', mcLater: '30' });
near(rewet.laterWidth, rewet.greenWidth, 'at fibre saturation the width is the green width again');

const steady = C.run({ width: '7.25', widthUnit: 'in', species: 'pine-loblolly', grain: 'flat',
  mcNow: '9', mcLater: '9' });
assert.equal(steady.change, 0, 'no moisture change, no movement');
near(steady.laterWidth, 7.25, 'the width is unchanged');
assert.equal(steady.perPoint, 0, 'movement per point is zero when the swing is zero');

// ---- Direction, monotonicity and the flat/quarter relationship.
const base = { width: '12', widthUnit: 'in', species: 'oak-northern-red', grain: 'flat' };
const shrink = C.run(Object.assign({}, base, { mcNow: '12', mcLater: '6' }));
const swell = C.run(Object.assign({}, base, { mcNow: '6', mcLater: '12' }));
assert.ok(shrink.change < 0 && swell.change > 0, 'drying shrinks, damp air swells');
// Hand-worked from the handbook relation with northern red oak's 8.6% tangential
// shrinkage: S(12%) = 8.6(1 - 12/30) = 5.16%, S(6%) = 6.88%, and the movement is
// 12 x ((1 - 0.0688)/(1 - 0.0516) - 1).
near(shrink.change, 12 * ((1 - 0.0688) / (1 - 0.0516) - 1), 'hand-worked red oak movement', 1e-12);
near(Math.abs(shrink.change) / 6, shrink.perPoint, 'per-point movement divides by the swing');
const quarter = C.run(Object.assign({}, base, { grain: 'quarter', mcNow: '12', mcLater: '6' }));
near(quarter.change, 12 * ((1 - 0.04 * (1 - 6 / 30)) / (1 - 0.04 * (1 - 12 / 30)) - 1),
  'hand-worked quarter-sawn movement', 1e-12);
assert.ok(Math.abs(quarter.change) < Math.abs(shrink.change), 'quarter-sawn moves less than flat-sawn');
const wider = C.run(Object.assign({}, base, { width: '24', mcNow: '12', mcLater: '6' }));
near(wider.change, shrink.change * 2, 'movement is proportional to width');
const halfSwing = C.run(Object.assign({}, base, { mcNow: '12', mcLater: '9' }));
const fullSwing = C.run(Object.assign({}, base, { mcNow: '12', mcLater: '6' }));
assert.ok(Math.abs(halfSwing.change) < Math.abs(fullSwing.change), 'a smaller swing moves less');

// ---- Unit handling: the same physical board in either unit agrees.
const inches = C.run({ width: '12', widthUnit: 'in', species: 'oak-white', grain: 'flat',
  mcNow: '6', mcLater: '14' });
const millimetres = C.run({ width: String(12 * 25.4), widthUnit: 'mm', species: 'oak-white', grain: 'flat',
  mcNow: '6', mcLater: '14' });
near(inches.change * 25.4, millimetres.change, 'inch and millimetre widths agree', 1e-9);
near(millimetres.widthMm, 12 * 25.4, 'millimetre equivalent of an entered width');
near(inches.changeAsPercent, millimetres.changeAsPercent, 'the percentage is unit-free');

// ---- Page contract: shared shell, accessible controls, no runtime foreign APIs.
assert.ok(!/fetch\(|XMLHttpRequest|localStorage|sessionStorage|indexedDB|WebSocket/.test(html), 'network or storage API found');
assert.ok(!/<script[^>]+src="https?:/i.test(html), 'remote script');
assert.ok(!/<link[^>]+href="https?:/i.test(html), 'remote stylesheet');
assert.ok(!/on(?:click|input|change|submit)=/i.test(html), 'inline handler');
assert.ok(!/\beval\s*\(|new\s+Function\b/.test(html), 'unsafe script evaluation');
assert.ok(html.includes('<form id="movement-form" novalidate>'), 'form missing');
assert.ok(html.includes('type="submit"'), 'submit missing');
assert.ok(html.includes('role="alert"'), 'error announcement missing');
assert.ok(html.includes('aria-live="polite" aria-atomic="true"'), 'result region missing');
assert.ok(html.includes('/assets/app.js') && html.includes('/assets/style.css'), 'shared shell assets missing');
for (const id of ['width', 'width-unit', 'species', 'grain', 'mc-now', 'mc-later']) {
  assert.ok(html.includes('for="' + id + '"'), 'missing label for ' + id);
  assert.ok(html.includes('id="' + id + '"'), 'missing control ' + id);
}
for (const id of ['movement-form', 'movement-err', 'movement-out']) {
  assert.ok(html.includes('id="' + id + '"'), 'missing id ' + id);
}
assert.ok(html.includes('<option value="mm">') && html.includes('<option value="in" selected>'), 'width unit options missing');
assert.ok(html.includes('<option value="flat" selected>') && html.includes('<option value="quarter">'), 'grain options missing');
assert.ok(!/style="[^"]*width:\s*\d{3,}px/.test(html), 'fixed wide inline styles');

console.log('wood-movement: 20 catalog cases, ' + fixture.vectors.length +
  ' reference vectors, identities, unit and page contracts passed');
