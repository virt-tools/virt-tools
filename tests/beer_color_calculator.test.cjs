/* Beer color: Morey's malt color units and SRM fit, the SRM/EBC scale relation,
   the published worked example, a fixture generated by an independent Python
   implementation, unit conversions, monotonicity, the catalog cases and the page
   contract. The page core is never compared with itself: every expected value
   comes from the Python reference in runtime/maintenance or from the catalog. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'beer-color-calculator';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* beer-color-core:start */';
const endMarker = '/* beer-color-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const coreSource = html.slice(start, end + endMarker.length);
assert.ok(!/document\.|window\./.test(coreSource), 'the core stays free of DOM access');
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreSource + '\nmodule.exports = BeerColorCore;', sandbox);
const C = sandbox.module.exports;

const near = (actual, expected, label) => {
  assert.ok(Math.abs(actual - expected) <= 1e-6,
    label + ': ' + actual + ' is not within 1e-6 of ' + expected);
};
const failure = (input) => {
  try { C.run(input); } catch (error) { return error.message; }
  return null;
};

// ---- Limits.
assert.equal(C.LITRES_PER_GALLON, 3.785411784);
assert.equal(C.POUNDS_PER_KG, 1 / 0.45359237);
assert.equal(C.MOREY_SCALE, 1.4922);
assert.equal(C.MOREY_EXPONENT, 0.6859);
assert.equal(C.MIN_VOLUME_L, 0.5);
assert.equal(C.MAX_VOLUME_L, 2000);
assert.equal(C.MIN_WEIGHT_KG, 0.001);
assert.equal(C.MAX_WEIGHT_KG, 500);
assert.equal(C.MIN_COLOR_L, 0.5);
assert.equal(C.MAX_COLOR_L, 2000);
assert.equal(C.MIN_COLOR_EBC, 1);
assert.equal(C.MAX_COLOR_EBC, 4000);
assert.equal(C.MAX_GRAINS, 12);

// ---- The published worked example from the cited article.
const published = C.run({
  volume: '5', volumeUnit: 'gal', weightUnit: 'lb', colorUnit: 'l',
  grains: [{ weight: '10', color: '1.8' }, { weight: '1', color: '60' }]
});
near(published.totalMcu, 15.6, 'published MCU');
assert.ok(Math.abs(published.srm - 9.8218) < 1e-3, 'published SRM ' + published.srm);
assert.equal(published.srm.toFixed(1), '9.8', 'the article rounds the same bill to 9.8 SRM');
near(published.ebc / published.srm, 25 / 12.7, 'EBC scale');
assert.equal(published.grains.length, 2);
near(published.grains[0].share + published.grains[1].share, 1, 'shares sum to one');
assert.equal(published.dominant, 2);

// ---- The independent Python fixture: random bills in every unit combination.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/beer_color_vectors.json'), 'utf8'));
assert.ok(fixture.vectors.length >= 60, 'fixture size');
near(fixture.published.mcu, 15.6, 'fixture published MCU');
for (const vector of fixture.vectors) {
  const label = vector.name || JSON.stringify(vector.input);
  // The fixture stores each grain as [weight, rating]; the page takes fields.
  const input = Object.assign({}, vector.input, {
    volume: String(vector.input.volume),
    grains: vector.input.grains.map(([weight, color]) => ({ weight: String(weight), color: String(color) }))
  });
  const result = C.run(input);
  for (const field of ['srm', 'ebc', 'totalMcu', 'totalKg', 'totalLb', 'litres', 'dominantShare']) {
    near(result[field], vector.expected[field], label + ' ' + field);
  }
  assert.equal(result.grains.length, vector.expected.shares.length, label + ' grain count');
  result.grains.forEach((grain, index) => {
    near(grain.share, vector.expected.shares[index], label + ' share ' + index);
    near(grain.mcu, grain.weightLb * grain.lovibond / result.gallons, label + ' MCU ' + index);
  });
  near(result.grains.reduce((sum, grain) => sum + grain.share, 0), 1, label + ' shares total');
  const dominant = result.grains.reduce((best, grain) => (grain.mcu > best.mcu ? grain : best));
  assert.equal(result.dominant, dominant.index, label + ' dominant grain');
}

// ---- The catalog cases, replayed through the documented input shape.
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const matches = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(matches.length, 1, 'slug must exist exactly once');
const entry = matches[0];
assert.equal(entry.name, 'Beer Color (SRM & EBC) Calculator');
assert.equal(entry.category, 'Food');
assert.equal(entry.subcategory, 'Estimation & Calculation');
assert.equal(entry.risk, 'low');
assert.equal(entry.maturity, 'draft');
assert.equal(entry.reviewedAt, null);
assert.equal(entry.listed, true);
assert.equal(entry.legacyCategory, null);
assert.equal(entry.icon, '\u{1F37A}');
assert.equal(new Set(entry.tags).size, entry.tags.length, 'duplicate tags');
assert.equal(new Set(entry.aliases).size, entry.aliases.length, 'duplicate aliases');
assert.ok(entry.method.length > 1200, 'method must document the formula and limits');
assert.equal(entry.sources.length, 2);
assert.equal(entry.sources[0].url, 'https://www.beerandbrewing.com/seeing-the-color-in-your-future');
assert.equal(entry.sources[1].url, 'https://en.wikipedia.org/wiki/Standard_Reference_Method');
assert.equal(entry.testCases.length, 20, 'catalog case count');
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'golden').length, 7);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'boundary').length, 3);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'validation').length, 10);

for (const testCase of entry.testCases) {
  if (testCase.kind === 'validation') {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.run(testCase.input);
  for (const [field, expected] of Object.entries(testCase.expected)) {
    near(result[field], expected, testCase.name + ' ' + field);
  }
}

// ---- Unit handling: the same physical bill in either system agrees.
const metric = C.run({
  volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4.5', color: '3.5' }, { weight: '0.4', color: '60' }]
});
const imperial = C.run({
  volume: String(20 / 3.785411784), volumeUnit: 'gal', weightUnit: 'lb', colorUnit: 'l',
  grains: [{ weight: String(4.5 * 2.2046226218487757), color: '3.5' },
    { weight: String(0.4 * 2.2046226218487757), color: '60' }]
});
assert.ok(Math.abs(metric.srm - imperial.srm) < 1e-9, 'metric and imperial bills must agree');
near(metric.totalKg, 4.9, 'total grain weight');
near(metric.litres, 20, 'litres');
near(metric.gallons, 20 / 3.785411784, 'gallons');

// A rating entered in EBC equals the same rating entered in Lovibond after conversion.
const lovibond = { volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '5', color: '60' }] };
const ebc = { volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'ebc',
  grains: [{ weight: '5', color: String(60 * 25 / 12.7) }] };
assert.ok(Math.abs(C.run(lovibond).srm - C.run(ebc).srm) < 1e-9, 'EBC and Lovibond entry agree');

// ---- Scaling: the sum is linear in weight and inverse in volume, the curve is not.
const single = C.run({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] });
const doubled = C.run({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '8', color: '10' }] });
near(doubled.totalMcu, single.totalMcu * 2, 'MCU is linear in grain weight');
near(doubled.srm, single.srm * Math.pow(2, 0.6859), 'SRM follows the power fit');
const diluted = C.run({ volume: '40', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] });
near(diluted.totalMcu, single.totalMcu / 2, 'MCU is inverse in batch volume');
assert.ok(doubled.srm > single.srm && single.srm > diluted.srm, 'more malt or less water is darker');
const roastier = C.run({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4', color: '350' }] });
assert.ok(roastier.srm > single.srm, 'a darker rating makes a darker beer');

// ---- Blank rows are ignored; edges of the API surface.
const mixed = C.run({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }, { weight: '', color: '' }, { weight: '  ', color: '' }] });
near(mixed.srm, single.srm, 'blank rows are ignored');
assert.equal(mixed.grains.length, 1);
assert.equal(failure({}), 'Add at least one grain to the bill.');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l', grains: [] }),
  'Add at least one grain to the bill.');
assert.equal(failure({ volume: '20', volumeUnit: 'L', weightUnit: 'KG', colorUnit: 'EBC',
  grains: [{ weight: '4', color: '20' }] }), null, 'units are case-insensitive');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'oz', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] }), 'Choose the grain weight unit.');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'srm',
  grains: [{ weight: '4', color: '10' }] }), 'Choose the colour rating unit.');
assert.equal(failure({ volume: '-20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] }),
  'Enter the batch volume as a number of litres, such as 20.');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '-1', color: '10' }] }),
  'Enter the grain weight for grain 1 as a number of kilograms, such as 4.5.');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l',
  grains: [{ weight: '0', color: '10' }] }),
  'Enter a grain weight from 0 to 500 kilograms for grain 1.');
assert.equal(failure({ volume: '529', volumeUnit: 'gal', weightUnit: 'lb', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] }),
  'Enter a batch volume from 0.13 to 528 US gallons.');
assert.equal(failure({ volume: '0.1', volumeUnit: 'gal', weightUnit: 'lb', colorUnit: 'l',
  grains: [{ weight: '4', color: '10' }] }),
  'Enter a batch volume from 0.13 to 528 US gallons.');
assert.equal(failure({ volume: '20', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'ebc',
  grains: [{ weight: '4', color: '0.5' }] }),
  'Enter a colour rating from 1 to 4,000 EBC for grain 1.');
const twelve = [];
for (let index = 0; index < 12; index += 1) twelve.push({ weight: '0.5', color: '2' });
assert.equal(C.run({ volume: '25', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l', grains: twelve }).grains.length, 12);
const thirteen = twelve.concat([{ weight: '0.5', color: '2' }]);
assert.equal(failure({ volume: '25', volumeUnit: 'l', weightUnit: 'kg', colorUnit: 'l', grains: thirteen }),
  'This page takes at most 12 malts.');

