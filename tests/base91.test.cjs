/* basE91 codec: replay the catalog fixtures, pin the published reference vectors,
   and compare the page core with a fixture generated by a Python port of Henke's
   reference C implementation. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'base91';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const start = html.indexOf('/* base91-core:start */');
const end = html.indexOf('/* base91-core:end */');
assert.ok(start > -1 && end > start, 'core markers missing');
const coreText = html.slice(start, html.indexOf('*/', end) + 2);
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreText + '\nmodule.exports = Base91Core;', sandbox);
const C = sandbox.module.exports;

const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const matches = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(matches.length, 1, 'slug must exist exactly once');
const entry = matches[0];
assert.equal(entry.name, 'Base91 Encoder / Decoder');
assert.equal(entry.category, 'Encoding');
assert.equal(entry.subcategory, 'General');
assert.equal(entry.risk, 'low');
assert.equal(entry.maturity, 'draft');
assert.equal(entry.reviewedAt, null);
assert.equal(entry.listed, true);
assert.equal(entry.legacyCategory, null);
assert.equal(new Set(entry.tags).size, entry.tags.length, 'duplicate tags');
assert.equal(new Set(entry.aliases).size, entry.aliases.length, 'duplicate aliases');
assert.ok(entry.method.length > 1200, 'method must document the bit queue and limits');
assert.equal(entry.sources.length, 2);
assert.equal(entry.sources[0].url, 'http://base91.sourceforge.net/');
assert.match(entry.sources[1].url, /^https:\/\//);
assert.equal(entry.testCases.length, 16, 'catalog case count');
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'golden').length, 7);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'boundary').length, 3);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'validation').length, 6);

// The catalog is the whole public surface: every listed record has a page directory.
const listed = catalog.tools.filter((tool) => tool.listed).length;
const directories = fs.readdirSync(path.join(root, 'frontend/tools'), { withFileTypes: true })
  .filter((entryInfo) => entryInfo.isDirectory() && fs.existsSync(path.join(root, 'frontend/tools', entryInfo.name, 'index.html')))
  .length;
assert.equal(listed, directories, 'listed records and page directories must agree');

function failure(input) {
  try { C.run(input); } catch (error) { return error.message; }
  return null;
}
for (const testCase of entry.testCases) {
  if (testCase.kind === 'validation') {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.run(testCase.input);
  for (const [field, expected] of Object.entries(testCase.expected)) {
    assert.equal(result[field], expected, testCase.name + ' ' + field);
  }
  if (result.mode === 'encode') {
    assert.equal(C.hex(C.decode(result.output).bytes), result.hex, testCase.name + ' round trip');
    assert.equal(result.output.length, result.outputUnits, testCase.name + ' output length');
    assert.ok(/^[A-Za-z0-9!#$%&()*+,./:;<=>?@[\]^_`{|}~"]+$/.test(result.output), testCase.name + ' alphabet only');
  } else {
    assert.equal(result.outputIsHex, !result.validUtf8, testCase.name + ' output kind');
  }
}

// The markup sample and the core default must not drift apart.
const sampleStart = html.indexOf('<textarea id="input"');
const sample = html.slice(html.indexOf('>', sampleStart) + 1, html.indexOf('</textarea>', sampleStart));
assert.equal(C.run({ input: sample }).output, C.run({}).output, 'default sample differs');
assert.equal(C.run({ mode: 'decode' }).output, 'Hello World!', 'decode default');

// Published reference vectors, pinned verbatim from upstream documentation.
assert.equal(C.encode(C.utf8Bytes('Hello World!')), '>OwJh>Io0Tv!8PE');
assert.equal(C.encode(C.parseHex('ECFBFC2754DB0C408223FA7917116867420EF60D')), 'y>)~Q7e.XL{xWWXI#WJ2CKy>A');
assert.equal(C.encode(C.utf8Bytes('This is a random binary string')), 'nX,<:WRT%yxtYQ:mbr4JB*H[LR/@Qj{o0aU=Z');

// Fixture generated by a Python port of the reference C encoder and decoder.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/base91_vectors.json'), 'utf8'));
assert.ok(fixture.vectors.length >= 100, 'fixture size');
for (const vector of fixture.vectors) {
  const bytes = vector.bytes ? C.parseHex(vector.bytes) : [];
  assert.equal(C.encode(bytes), vector.base91, 'fixture encoding ' + vector.bytes);
  assert.equal(C.hex(C.decode(vector.base91).bytes), vector.bytes, 'fixture decoding ' + vector.base91);
  assert.equal(C.decode(vector.base91).ignored, 0, 'fixture is pure alphabet');
}
for (const wrapped of fixture.wrapped) {
  const decoded = C.decode(wrapped.text);
  assert.equal(C.hex(decoded.bytes), wrapped.bytes, 'wrapped payload ' + JSON.stringify(wrapped.text));
  assert.equal(decoded.ignored, wrapped.ignored, 'ignored count ' + JSON.stringify(wrapped.text));
}

// UTF-8 handling agrees with the platform encoder and decoder.
for (const text of ['a', 'h\u00e9llo \ud83c\udf0d', '\u65e5\u672c\u8a9e\u30c6\u30ad\u30b9\u30c8', '\ud83d\ude00\ud83d\ude03', '\u0000\u0001']) {
  const encoded = C.run({ mode: 'encode', input: text });
  assert.equal(encoded.hex, C.hex(Array.from(new TextEncoder().encode(text))), 'utf8 encoding ' + text);
  const decoded = C.run({ mode: 'decode', input: encoded.output });
  assert.equal(decoded.output, text, 'utf8 round trip ' + text);
  assert.equal(decoded.validUtf8, true);
}
assert.equal(C.hex(C.utf8Bytes('\ud800')), 'EFBFBD', 'lone high surrogate becomes U+FFFD');
assert.equal(C.hex(C.utf8Bytes('\udc00x')), 'EFBFBD78', 'lone low surrogate becomes U+FFFD');
for (const bytes of [[0xff], [0x80], [0xc0, 0xaf], [0xed, 0xa0, 0x80], [0xf4, 0x90, 0x80, 0x80], [0xc3]]) {
  assert.equal(C.utf8Text(bytes), null, 'invalid UTF-8 accepted: ' + C.hex(bytes));
}

// Alphabet and API edges.
assert.equal(C.alphabet.length, 91);
assert.equal(new Set(C.alphabet).size, 91);
for (const code of [0x20, 0x27, 0x5c, 0x7f]) assert.ok(!C.alphabet.includes(String.fromCharCode(code)), 'excluded character present');
assert.equal(C.encode([]), '', 'the empty payload stays empty at the API boundary');
assert.equal(C.decode('').bytes.length, 0);
assert.equal(C.hex(C.parseHex('00\r\nff\t10 20')), '00FF1020');
assert.equal(C.run({ mode: 'encode', input: '00 0A', hex: true }).output, C.run({ mode: 'encode', input: C.hex(C.parseHex('000a')), hex: true }).output);
assert.throws(() => C.encode([256]));
assert.throws(() => C.encode([-1]));
assert.throws(() => C.encode([1.5]));
assert.equal(failure({ mode: 'encode', input: 'x'.repeat(100001) }), 'Input must be 100,000 characters or fewer.');
assert.equal(failure({ mode: 'decode', input: 'A'.repeat(100002) }), 'Input must be 100,000 characters or fewer.');
assert.ok(C.run({ mode: 'encode', input: 'x'.repeat(100000) }).output.length > 100000, 'the documented limit is inclusive');
assert.equal(C.run({ mode: 'decode', input: 'A'.repeat(100000) }).outputUnits > 0, true);

// Page contract: shared shell, accessible controls and no runtime foreign APIs.
assert.ok(!/fetch\(|XMLHttpRequest|localStorage|sessionStorage|indexedDB|WebSocket/.test(html), 'network or storage API found');
assert.ok(!/<script[^>]+src="https?:/i.test(html), 'remote script');
assert.ok(!/<link[^>]+href="https?:/i.test(html), 'remote stylesheet');
assert.ok(!/on(?:click|input|change|submit)=/i.test(html), 'inline handler');
assert.ok(!/\beval\s*\(|new\s+Function\b/.test(html), 'unsafe script evaluation');
assert.ok(html.includes('for="input"'), 'input label missing');
assert.ok(html.includes('for="hex-mode"'), 'checkbox label missing');
assert.ok(html.includes('aria-describedby="input-help"'), 'help reference missing');
assert.ok(html.includes('aria-pressed="true"'), 'direction button state missing');
for (const match of html.matchAll(/\$\("([a-z0-9-]+)"\)/g)) {
  assert.ok(html.includes('id="' + match[1] + '"'), 'script references missing id ' + match[1]);
}
assert.ok(html.includes('<form id="codec-form" novalidate>'), 'form missing');
assert.ok(html.includes('type="submit"'), 'submit missing');
assert.ok(html.includes('id="reset"'), 'reset missing');
assert.ok(html.includes('id="output" readonly'), 'read-only output missing');
assert.ok(html.includes('role="alert"'), 'error announcement missing');
assert.ok(html.includes('role="status" aria-live="polite"'), 'result announcement missing');
assert.ok(html.includes('/assets/app.js') && html.includes('/assets/style.css'), 'shared shell assets missing');

console.log('base91: 16 catalog cases, 3 published vectors, ' + fixture.vectors.length + ' reference vectors, and the page contract passed');
