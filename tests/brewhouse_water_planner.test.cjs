/* Brewhouse water planner: the backwards water balance, the published strike and
   absorption relations, a fixture generated by an independent Python implementation,
   unit agreement, monotonicity, the catalog cases and the page contract. The page core
   is never compared with itself: every expected value comes from the Python reference
   in runtime/maintenance or from the catalog. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'brewhouse-water-planner';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* brewhouse-water-core:start */';
const endMarker = '/* brewhouse-water-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const coreSource = html.slice(start, end + endMarker.length);
assert.ok(!/document\.|window\./.test(coreSource), 'the core stays free of DOM access');
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreSource + '\nmodule.exports = BrewhouseWaterCore;', sandbox);
const C = sandbox.module.exports;

const near = (actual, expected, label, tolerance) => {
  const limit = tolerance === undefined ? 1e-6 : tolerance;
  assert.ok(Math.abs(actual - expected) <= limit,
    label + ': ' + actual + ' is not within ' + limit + ' of ' + expected);
};
const failure = (input) => {
  try { C.run(input); } catch (error) { return error.message; }
  return null;
};

// ---- Limits and physical constants.
assert.equal(C.LITRES_PER_GALLON, 3.785411784);
assert.equal(C.KG_PER_POUND, 0.45359237);
assert.equal(C.LITRES_PER_QUART, 0.946352946);
near(C.LITRES_PER_KG_PER_QT_PER_LB, 2.086351113, 'qt/lb to L/kg', 1e-9);
assert.equal(C.SHRINKAGE, 0.96);
assert.equal(C.MIN_BATCH_L, 1);
assert.equal(C.MAX_BATCH_L, 2000);
assert.equal(C.MIN_GRAIN_KG, 0.1);
assert.equal(C.MAX_GRAIN_KG, 500);
assert.equal(C.MIN_THICKNESS, 1);
assert.equal(C.MAX_THICKNESS, 10);
assert.equal(C.MIN_BOIL_MIN, 1);
assert.equal(C.MAX_BOIL_MIN, 300);
assert.equal(C.MIN_BOIL_OFF_LH, 0.1);
assert.equal(C.MAX_BOIL_OFF_LH, 50);
assert.equal(C.MIN_TRUB_L, 0);
assert.equal(C.MAX_TRUB_L, 100);
assert.equal(C.MIN_ABSORPTION, 0.3);
assert.equal(C.MAX_ABSORPTION, 2);

// ---- The published relations from the cited batch-sparging guide.
const published = C.run({
  unit: 'us', batch: '5.5', grain: '12', thickness: '1.5', boilTime: '60',
  boilOff: '1.5', trub: '0', absorption: '0.4'
});
// 12 lb at 1.5 qt/lb is 18 quarts, or 4.5 US gallons, of strike water.
near(published.strikeL / C.LITRES_PER_GALLON, 4.5, 'published strike water', 1e-9);
// 12 lb of grain at 0.1 gal/lb absorbs 1.2 gallons.
near(published.absorbedL / C.LITRES_PER_GALLON, 1.2, 'published absorption', 1e-9);
// 6 gallons into the kettle plus a 1.5 gal/h boil for an hour is a 7.5 gallon pre-boil;
// here 5.5 gallons cold and no kettle loss make 5.729 hot gallons and 7.229 pre-boil.
near(published.preBoilL / C.LITRES_PER_GALLON, (5.5 / 0.96) + 1.5, 'pre-boil chain', 1e-9);

// ---- The independent Python fixture: random batches in both unit systems.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/brewhouse_water_vectors.json'), 'utf8'));
assert.ok(fixture.vectors.length >= 60, 'fixture size');
for (const vector of fixture.vectors) {
  const result = C.run(vector.input);
  for (const [field, expected] of Object.entries(vector.expected)) {
    near(result[field], expected, vector.name + ' ' + field, 1e-6);
  }
}

// ---- The catalog cases, replayed through the documented input shape.
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const matches = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(matches.length, 1, 'slug must exist exactly once');
const entry = matches[0];
assert.equal(entry.name, 'Brewhouse Water Planner');
assert.equal(entry.category, 'Food');
assert.equal(entry.subcategory, 'Planning');
assert.equal(entry.risk, 'moderate');
assert.equal(entry.maturity, 'draft');
assert.equal(entry.reviewedAt, null);
assert.equal(entry.listed, true);
assert.equal(entry.legacyCategory, null);
assert.equal(entry.icon, '\u{1F4A7}');
assert.equal(new Set(entry.tags).size, entry.tags.length, 'duplicate tags');
assert.equal(new Set(entry.aliases).size, entry.aliases.length, 'duplicate aliases');
assert.ok(entry.method.length > 1200, 'method must document the formula and limits');
assert.equal(entry.sources.length, 3);
assert.equal(entry.sources[0].url, 'https://www.homebrewersassociation.org/wp-content/uploads/How-To-Batch-Sparge.pdf');
assert.equal(entry.sources[1].url, 'https://howtobrew.com/section-3/chapter-17');
assert.equal(entry.sources[2].url, 'https://en.wikipedia.org/wiki/Properties_of_water');
assert.equal(entry.testCases.length, 22, 'catalog case count');
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'golden').length, 7);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'boundary').length, 3);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'validation').length, 12);

for (const testCase of entry.testCases) {
  if (testCase.kind === 'validation') {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.run(testCase.input);
  for (const [field, expected] of Object.entries(testCase.expected)) {
    near(result[field], expected, testCase.name + ' ' + field, 2e-6);
  }
}

// ---- The same physical brew in either unit system agrees.
const metric = C.run({
  unit: 'metric', batch: '20', grain: '5', thickness: '3', boilTime: '75',
  boilOff: '3.5', trub: '1.2', absorption: '1'
});
const us = C.run({
  unit: 'us',
  batch: String(20 / C.LITRES_PER_GALLON),
  grain: String(5 / C.KG_PER_POUND),
  thickness: String(3 / C.LITRES_PER_KG_PER_QT_PER_LB),
  boilTime: '75',
  boilOff: String(3.5 / C.LITRES_PER_GALLON),
  trub: String(1.2 / C.LITRES_PER_GALLON),
  absorption: String(1 / C.LITRES_PER_KG_PER_QT_PER_LB)
});
for (const field of ['batchL', 'grainKg', 'thicknessLkg', 'coldL', 'hotL', 'preBoilL',
  'absorbedL', 'totalL', 'strikeL', 'spargeL', 'firstRunningsL']) {
  near(us[field], metric[field], 'unit agreement ' + field, 1e-9);
}

// ---- The chain itself: cooling, boiling and absorption only add water.
near(metric.hotL, metric.coldL / 0.96, 'hot is the cold volume divided by the shrinkage');
near(metric.coldL, metric.batchL + metric.trubL, 'cold volume adds the kettle loss');
near(metric.preBoilL, metric.hotL + metric.boilOffTotalL, 'pre-boil adds the boil-off');
near(metric.totalL, metric.preBoilL + metric.absorbedL, 'total adds the absorption');
near(metric.strikeL + metric.spargeL, metric.totalL, 'strike plus sparge is the total');
near(metric.firstRunningsL, metric.strikeL - metric.absorbedL, 'first runnings are strike less absorption');

// The 4 percent shrinkage agrees with water density at the boil and at pitching.
const DENSITY_RATIO = 958.4 / 998.2;
assert.ok(Math.abs((1 - C.SHRINKAGE) - (1 - DENSITY_RATIO)) < 0.0005, 'shrinkage matches water density');

// ---- Monotonicity: more of each loss asks for more water.
const base = { unit: 'metric', batch: '20', grain: '5', thickness: '3', boilTime: '60',
  boilOff: '3', trub: '1', absorption: '1' };
const more = (patch) => C.run(Object.assign({}, base, patch));
assert.ok(more({ boilTime: '90' }).totalL > more({}).totalL, 'a longer boil needs more water');
assert.ok(more({ boilOff: '5' }).totalL > more({}).totalL, 'a faster boil-off needs more water');
assert.ok(more({ trub: '2' }).totalL > more({}).totalL, 'a bigger kettle loss needs more water');
assert.ok(more({ absorption: '1.2' }).totalL > more({}).totalL, 'thirstier grain needs more water');
assert.ok(more({ grain: '6' }).totalL > more({}).totalL, 'a bigger grain bill needs more water');
near(more({ thickness: '4' }).totalL, more({}).totalL, 'mash thickness moves strike against sparge, not the total');
assert.ok(more({ thickness: '4' }).strikeL > more({}).strikeL, 'a thicker mash uses more strike water');
assert.ok(more({ thickness: '4' }).spargeL < more({}).spargeL, 'a thicker mash leaves less to sparge');
assert.ok(more({ batch: '25' }).totalL > more({}).totalL, 'a bigger batch needs more water');

// ---- Edges: a zero sparge is accepted; a negative one is refused with a way out.
const noSparge = C.run({ unit: 'metric', batch: '12', grain: '2.5', thickness: '7.2',
  boilTime: '60', boilOff: '3', trub: '0', absorption: '1' });
assert.equal(noSparge.spargeL, 0, 'a full-volume mash has no sparge');
assert.equal(noSparge.totalL, noSparge.strikeL, 'strike carries the whole batch');
assert.equal(failure({ unit: 'metric', batch: '10', grain: '8', thickness: '3',
  boilTime: '60', boilOff: '3', trub: '1', absorption: '1' }),
  'The mash water is more than the whole batch needs. Lower the mash thickness or raise the batch volume.');
assert.equal(failure({}), 'Choose the unit system.');
assert.equal(failure({ unit: 'metric' }), 'Enter the batch volume.');
assert.equal(failure({ unit: 'metric', batch: '19', grain: '4.5', thickness: '3',
  boilTime: '60', boilOff: '3', trub: '', absorption: '1' }), 'Enter the kettle loss.');

// ---- Page contract: shared shell, accessible controls, no runtime foreign APIs.
assert.ok(!/fetch\(|XMLHttpRequest|localStorage|sessionStorage|indexedDB|WebSocket/.test(html), 'network or storage API found');
assert.ok(!/<script[^>]+src="https?:/i.test(html), 'remote script');
assert.ok(!/<link[^>]+href="https?:/i.test(html), 'remote stylesheet');
assert.ok(!/on(?:click|input|change|submit)=/i.test(html), 'inline handler');
assert.ok(!/\beval\s*\(|new\s+Function\b/.test(html), 'unsafe script evaluation');
assert.ok(html.includes('<form id="water-form" novalidate>'), 'form missing');
assert.ok(html.includes('type="submit"'), 'submit missing');
assert.ok(html.includes('role="alert"'), 'error announcement missing');
assert.ok(html.includes('aria-live="polite" aria-atomic="true"'), 'result region missing');
assert.ok(html.includes('/assets/app.js') && html.includes('/assets/style.css'), 'shared shell assets missing');
assert.ok(html.includes('<option value="us">'), 'US unit option missing');
for (const id of ['water-form', 'unit', 'batch', 'grain', 'thickness', 'boil-time', 'boil-off',
  'trub', 'absorption', 'water-err', 'water-out', 'batch-label', 'grain-label',
  'thickness-label', 'boil-off-label', 'trub-label', 'absorption-label']) {
  assert.ok(html.includes('id="' + id + '"'), 'missing id ' + id);
}
for (const id of ['batch', 'grain', 'thickness', 'boil-time', 'boil-off', 'trub', 'absorption']) {
  assert.ok(html.includes('for="' + id + '"'), 'missing label for ' + id);
}
assert.ok(!/style="[^"]*width:\s*\d{3,}px/.test(html), 'fixed wide inline styles');

console.log('brewhouse-water: 22 catalog cases, ' + fixture.vectors.length +
  ' reference vectors, published relations, unit and page contracts passed');
