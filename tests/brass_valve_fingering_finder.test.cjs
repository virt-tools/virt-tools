/* Brass valve fingering finder: the published valve-combination table as the
   external oracle, a fixture generated by an independent Python model (which
   builds the valve lengths itself), the catalog cases, the identities that
   follow from adding tube lengths, and the page contract. No expected number
   comes from the page. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'brass-valve-fingering-finder';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* brass-core:start */';
const endMarker = '/* brass-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const coreSource = html.slice(start, end + endMarker.length);
assert.ok(!/document\.|window\./.test(coreSource), 'the core stays free of DOM access');
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreSource + '\nmodule.exports = BrassCore;', sandbox);
const C = sandbox.module.exports;

const near = (actual, expected, label, relative) => {
  const rel = relative === undefined ? 1e-9 : relative;
  assert.ok(Number.isFinite(actual), label + ': ' + actual + ' is not a finite number');
  assert.ok(Math.abs(actual - expected) <= rel * Math.max(1, Math.abs(expected)),
    label + ': ' + actual + ' is not within ' + rel + ' of ' + expected);
};
const failure = (input) => {
  try { C.analyze(input); } catch (error) { return error.message; }
  return null;
};
const base = { instrument: 'bb-trumpet', note: 'C4' };

// ---- Constants: the three-valve layout the page claims to model.
assert.equal(C.A4, 440);
assert.equal(C.TOLERANCE, 50);
assert.deepEqual(Array.from(C.HARMONICS), [2, 3, 4, 5, 6, 7, 8]);
assert.equal(C.VALVES['1'], 1 / 8);
assert.equal(C.VALVES['2'], 1 / 15);
assert.equal(C.VALVES['3'], 1 / 5);
assert.equal(C.COMBOS.length, 8);
assert.deepEqual(Array.from(C.COMBOS, (combo) => combo.id),
  ['Open', '1', '2', '3', '1-2', '2-3', '1-3', '1-2-3']);
assert.deepEqual(Object.keys(C.INSTRUMENTS).sort(), ['bb-cornet', 'bb-flugelhorn', 'bb-trumpet', 'f-horn']);
for (const spec of Object.values(C.INSTRUMENTS)) {
  assert.equal(typeof spec.label, 'string');
  assert.ok(Number.isInteger(spec.pedal) && Number.isInteger(spec.offset));
}

// ---- The published table is the oracle: every row's ratio is an exact rational.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/brass_valve_vectors.json'), 'utf8'));
assert.equal(fixture.table.length, 17, 'published table rows');
for (const row of fixture.table) {
  const combo = C.COMBOS.find((candidate) => candidate.id === row.valves);
  assert.ok(combo, 'no combination named ' + row.valves);
  const produced = row.harmonic * C.factor(combo.valves) / 2;
  const [numerator, denominator] = row.ratio.split(':').map(Number);
  near(produced, numerator / denominator, 'published ratio ' + row.valves + ' h' + row.harmonic, 1e-12);
  const cents = 1200 * Math.log2(produced);
  assert.ok(Math.abs(cents - row.cents) <= 0.5, 'published cents ' + row.valves + ' h' + row.harmonic);
  const fromEt = cents - Math.round(cents / 100) * 100;
  assert.ok(Math.abs(fromEt - row.centsFromEt) <= 0.5,
    'published cents from 12-ET ' + row.valves + ' h' + row.harmonic);
}

// ---- Identities that follow from adding tube lengths rather than intervals.
const lowering = (label) => -1200 * Math.log2(C.factor(C.COMBOS.find((c) => c.id === label).valves));
near(lowering('1'), 203.91, 'the first valve lowers 9:8', 1e-4);
near(lowering('2'), 111.731, 'the second valve lowers 16:15', 1e-4);
near(lowering('3'), 315.641, 'the third valve lowers 6:5', 1e-4);
near(lowering('Open'), 0, 'open tubing adds nothing');
assert.ok(Math.abs(lowering('1-2') - lowering('3')) < 20, '1-2 and 3 are the same interval to within a fifth of a semitone');
assert.ok(lowering('1-2') < 300 + 4 && lowering('1-2') > 300, '1-2 comes in near three semitones');
assert.ok(lowering('1-2-3') < 600 && lowering('1-2-3') > 570, '1-2-3 comes in near six semitones');
assert.ok(lowering('1-3') > 480 && lowering('1-3') < 500, '1-3 is short of a perfect fourth');
assert.ok(lowering('1-2-3') < 600 - 25, '1-2-3 is more than a quarter tone short of a tritone');
for (const combo of C.COMBOS) {
  const value = C.factor(combo.valves);
  assert.ok(value > 0.7 && value <= 1, combo.id + ' factor out of range');
}
// A longer combination always sounds lower than a shorter one that contains it.
assert.ok(C.factor([1, 3]) < C.factor([1]) && C.factor([1, 2, 3]) < C.factor([1, 2]));

// ---- The independent Python fixture: every written note on every instrument.
for (const vector of fixture.vectors) {
  const result = C.analyze(vector.input);
  const want = vector.expected;
  assert.equal(result.written.midi, want.written.midi, vector.name + ' written midi');
  assert.equal(result.written.name, want.written.name, vector.name + ' written name');
  assert.equal(result.sounding.midi, want.sounding.midi, vector.name + ' sounding midi');
  assert.equal(result.sounding.name, want.sounding.name, vector.name + ' sounding name');
  near(result.sounding.frequency, want.sounding.frequency, vector.name + ' sounding frequency');
  near(result.pedal.frequency, want.pedal.frequency, vector.name + ' pedal frequency');
  assert.equal(result.pedal.name, want.pedal.name, vector.name + ' pedal name');
  assert.equal(result.options.length, want.options.length, vector.name + ' option count');
  want.options.forEach((expected, index) => {
    const got = result.options[index];
    assert.equal(got.valves, expected.valves, vector.name + ' option ' + index + ' valves');
    assert.equal(got.fingering, expected.fingering, vector.name + ' option ' + index + ' fingering');
    assert.equal(got.harmonic, expected.harmonic, vector.name + ' option ' + index + ' harmonic');
    near(got.cents, expected.cents, vector.name + ' option ' + index + ' cents');
    near(got.frequency, expected.frequency, vector.name + ' option ' + index + ' frequency');
    assert.ok(Math.abs(got.cents) <= C.TOLERANCE, vector.name + ': a listed option is outside the window');
  });
  // Every listed option is sorted by absolute deviation and stays inside the window.
  for (let i = 1; i < result.options.length; i++) {
    assert.ok(Math.abs(result.options[i - 1].cents) <= Math.abs(result.options[i].cents),
      vector.name + ': options are not sorted by deviation');
  }
  // The open series is the same on every instrument in written pitch.
  assert.equal(Array.from(result.openSeries, (row) => row.written).join(','),
    Array.from(fixture.series['bb-trumpet'], (row) => row.written).join(','),
    vector.name + ': the written open series is instrument independent');
}

// ---- The open series, sounding names and deviations.
for (const [instrument, rows] of Object.entries(fixture.series)) {
  const result = C.series(C.INSTRUMENTS[instrument]);
  assert.equal(result.length, rows.length, instrument + ' series length');
  rows.forEach((want, index) => {
    assert.equal(result[index].harmonic, want.harmonic, instrument + ' series harmonic');
    assert.equal(result[index].written, want.written, instrument + ' series written');
    assert.equal(result[index].sounding, want.sounding, instrument + ' series sounding');
    near(result[index].cents, want.cents, instrument + ' series cents ' + want.harmonic);
    near(result[index].frequency, want.frequency, instrument + ' series frequency ' + want.harmonic);
  });
}
const trumpetSeries = C.series(C.INSTRUMENTS['bb-trumpet']);
assert.equal(Array.from(trumpetSeries, (row) => row.written).join(','), 'C4,G4,C5,E5,G5,Bb5,C6',
  'the written bugle series');
near(trumpetSeries[3].cents, -13.686, 'the fifth harmonic is 13.7 cents flat', 1e-4);
near(trumpetSeries[5].cents, -31.174, 'the seventh harmonic is 31.2 cents flat', 1e-4);
near(trumpetSeries[1].cents, 1.955, 'the open third harmonic is two cents sharp', 1e-3);
const hornSeries = C.series(C.INSTRUMENTS['f-horn']);
assert.equal(hornSeries[0].sounding, 'F3', 'an F horn sounds a fifth below its written C4');
assert.equal(hornSeries[0].written, 'C4');

// ---- Range: derived from the layout, not asserted from a chart.
