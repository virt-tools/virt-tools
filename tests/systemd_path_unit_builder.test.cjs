const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const slug = 'systemd-path-unit-builder';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* systemd-path-core:start */';
const endMarker = '/* systemd-path-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const sandbox = {module: {}};
vm.createContext(sandbox);
vm.runInContext(html.slice(start, end + endMarker.length) + '\nmodule.exports = SystemdPathCore;', sandbox);
const C = sandbox.module.exports;

const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const records = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(records.length, 1, 'catalog must contain exactly one path unit builder');
const record = records[0];
assert.equal(record.name, 'systemd Path Unit Builder');
assert.equal(record.category, 'System');
assert.equal(record.subcategory, 'Generation');
assert.equal(record.risk, 'low');
assert.equal(record.maturity, 'draft');
assert.equal(record.reviewedAt, null);
assert.equal(record.listed, true);
assert.equal(record.legacyCategory, null);
assert.equal(new Set(record.tags).size, record.tags.length);
assert.equal(new Set(record.aliases).size, record.aliases.length);
assert.ok(record.method.length > 700, 'method documents syntax, semantics and limitations');
assert.equal(record.sources.length, 2);
for (const source of record.sources) assert.match(source.url, /^https:\/\//);
assert.equal(record.testCases.length, 23);
assert.equal(record.testCases.filter((t) => t.kind === 'golden').length, 6);
assert.equal(record.testCases.filter((t) => t.kind === 'boundary').length, 3);
assert.equal(record.testCases.filter((t) => t.kind === 'validation').length, 14);

function failure(input) {
  try { C.build(input); } catch (error) { return error.message; }
  return null;
}
function checkContains(text, values, label, unexpected = false) {
  for (const value of values || []) assert.equal(text.includes(value), !unexpected, `${label}: ${unexpected ? 'unexpected' : 'missing'} ${JSON.stringify(value)}`);
}
for (const testCase of record.testCases) {
  if (testCase.kind === 'validation') {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.build(testCase.input);
  for (const key of ['pathFilename', 'serviceFilename', 'pathUnit', 'serviceUnit', 'pathCount', 'trigger', 'execStart']) {
    if (testCase.expected[key] !== undefined) assert.equal(result[key], testCase.expected[key], `${testCase.name}: ${key}`);
  }
  checkContains(result.pathUnit, testCase.expected.containsPath, testCase.name + ' path');
  checkContains(result.serviceUnit, testCase.expected.containsService, testCase.name + ' service');
  checkContains(result.pathUnit, testCase.expected.excludesPath, testCase.name + ' path', true);
  checkContains(result.serviceUnit, testCase.expected.excludesService, testCase.name + ' service', true);
  assert.equal(Array.from(result.paths).length, result.pathCount, testCase.name + ' path count');
  assert.ok(result.pathUnit.includes('Unit=' + result.serviceFilename + '\n'), testCase.name + ' explicit service link');
  assert.ok(result.serviceUnit.includes('Type=oneshot\n'), testCase.name + ' oneshot service');
  assert.ok(!result.serviceUnit.includes('Restart='), testCase.name + ' no restart loop');
  assert.ok(!result.serviceUnit.includes('[Install]'), testCase.name + ' service is activated by path');
}

// Independent small unit-file parser: validate section placement and cardinality
// rather than merely comparing strings generated by the same formatter.
function parseUnit(text) {
  const result = {};
  let section = null;
  for (const line of text.split('\n')) {
    if (!line) continue;
    const sectionMatch = line.match(/^\[([A-Za-z]+)\]$/);
    if (sectionMatch) { section = sectionMatch[1]; result[section] ||= []; continue; }
    assert.ok(section, 'directive outside section');
    const equals = line.indexOf('=');
    assert.ok(equals > 0, 'malformed directive ' + line);
    result[section].push([line.slice(0, equals), line.slice(equals + 1)]);
  }
  return result;
}
for (const trigger of ['PathExists', 'PathExistsGlob', 'PathChanged', 'PathModified', 'DirectoryNotEmpty']) {
  const built = C.build({trigger, paths: '/tmp/a\n/tmp/b b\n/tmp/100%'});
  const parsed = parseUnit(built.pathUnit);
  assert.deepEqual(Object.keys(parsed), ['Unit', 'Path', 'Install']);
  const watches = parsed.Path.filter(([key]) => key === trigger);
  assert.equal(watches.length, 3);
  assert.deepEqual(watches.map((entry) => entry[1]), ['/tmp/a', '/tmp/b\\x20b', '/tmp/100%%']);
  assert.equal(parsed.Path.filter(([key]) => key === 'Unit')[0][1], built.serviceFilename);
  assert.equal(parsed.Install[0][0], 'WantedBy');
  assert.equal(parsed.Install[0][1], 'multi-user.target');
}
for (const value of ['0', '500ms', '2s', '1min', '1h 30min', '1.5 seconds']) assert.equal(C.duration(value), value);
for (const value of ['', '-1s', '1e3s', 'infinity', '5fortnights', '5', null, {}]) assert.throws(() => C.duration(value));
for (const value of ['0', '1', '200', '1000000']) assert.equal(C.burst(value), value);
for (const value of ['', '00', '01', '-1', '1000001', '1.5', null]) assert.throws(() => C.burst(value));
assert.equal(C.pathValue('/tmp/a"b 100%'), '/tmp/a\\x22b\\x20100%%');
assert.equal(C.quoteExec('$HOME 100% a"b\\c'), '"$$HOME 100%% a\\"b\\\\c"');

// Markup defaults and the replayable core defaults must agree.
function textareaValue(id) {
  const at = html.indexOf('<textarea id="' + id + '"');
  return html.slice(html.indexOf('>', at) + 1, html.indexOf('</textarea>', at));
}
function inputValue(id) {
  const tag = html.slice(html.indexOf('<input id="' + id + '"'));
  return tag.slice(0, tag.indexOf('>')).match(/value="([^"]*)"/)[1];
}
const defaultResult = C.build({});
assert.equal(defaultResult.pathUnit, C.build({paths: textareaValue('in-paths')}).pathUnit);
assert.equal(defaultResult.serviceUnit, C.build({arguments: textareaValue('in-arguments')}).serviceUnit);
assert.equal(defaultResult.base, inputValue('in-name'));
assert.equal(defaultResult.trigger, 'DirectoryNotEmpty');

