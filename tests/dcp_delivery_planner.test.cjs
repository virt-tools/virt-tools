/* DCP delivery planning: the DCI container and bit-rate arithmetic, a fixture
   generated by an independent Python reference (exact rational arithmetic),
   the catalog cases, the identities that follow from the model, and the page
   contract. No expected number comes from the page. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const slug = 'dcp-delivery-planner';
const html = fs.readFileSync(path.join(root, 'frontend/tools', slug, 'index.html'), 'utf8');
const startMarker = '/* dcpplanner-core:start */';
const endMarker = '/* dcpplanner-core:end */';
const start = html.indexOf(startMarker);
const end = html.indexOf(endMarker);
assert.ok(start > -1 && end > start, 'core markers missing');
const coreSource = html.slice(start, end + endMarker.length);
assert.ok(!/document\.|window\./.test(coreSource), 'the core stays free of DOM access');
const sandbox = { module: {} };
vm.createContext(sandbox);
vm.runInContext(coreSource + '\nmodule.exports = DcpCore;', sandbox);
const C = sandbox.module.exports;

const near = (actual, expected, label, relative) => {
  const rel = relative === undefined ? 1e-9 : relative;
  assert.ok(Number.isFinite(actual), label + ': ' + actual + ' is not a finite number');
  assert.ok(Math.abs(actual - expected) <= rel * Math.max(1, Math.abs(expected)),
    label + ': ' + actual + ' is not within ' + rel + ' of ' + expected);
};
const failure = (input) => {
  try { C.analyze(input); } catch (error) { return error.message; }
  return null;
};
const base = {
  runtime: '2:00:00', container: '2k', picture: 'flat', fps: '24',
  imageRate: '150', channels: '6', sampleRate: '48', stereo: false, drive: '1000',
};
const fields = {
  barsAxis: (result) => result.bars.axis,
  barsPerSide: (result) => result.bars.perSide,
};

// ---- The DCI constants the model turns on.
assert.equal(C.CEILING_MBIT, 250);
assert.equal(C.OVERHEAD, 0.01);
assert.equal(JSON.stringify(C.STEREO_RATES), JSON.stringify([24, 48]));
assert.equal(JSON.stringify(C.DRIVES), JSON.stringify([250, 500, 1000, 2000]));
assert.equal(JSON.stringify(C.CONTAINERS['2k'].rates), JSON.stringify([24, 25, 30, 48, 50, 60]));
assert.equal(JSON.stringify(C.CONTAINERS['4k'].rates), JSON.stringify([24, 25, 30]));
assert.equal(C.CONTAINERS['2k'].width, 2048);
assert.equal(C.CONTAINERS['4k'].height, 2160);
assert.equal(JSON.stringify(C.ACTIVE['2k'].flat), JSON.stringify([1998, 1080]));
assert.equal(JSON.stringify(C.ACTIVE['2k'].scope), JSON.stringify([2048, 858]));
assert.equal(JSON.stringify(C.ACTIVE['4k'].flat), JSON.stringify([3996, 2160]));
assert.equal(JSON.stringify(C.ACTIVE['4k'].scope), JSON.stringify([4096, 1716]));
assert.equal(JSON.stringify(C.LIMITS.channels), JSON.stringify([1, 16]));
assert.equal(JSON.stringify(C.LIMITS.seconds), JSON.stringify([1, 28800]));

// ---- Parsing and the exact user-facing messages.
assert.equal(failure({ ...base, runtime: '' }), 'Enter the runtime as h:mm:ss or mm:ss.');
assert.equal(failure({ ...base, runtime: '120 min' }), 'Runtime must be h:mm:ss or mm:ss.');
assert.equal(failure({ ...base, runtime: '1:75:00' }), 'Runtime must be h:mm:ss or mm:ss, with minutes and seconds under 60.');
assert.equal(failure({ ...base, runtime: '0:00' }), 'Runtime must be at least one second.');
assert.equal(failure({ ...base, runtime: '9:00:00' }), 'Runtime must be 8 hours or less.');
assert.equal(failure({ ...base, container: '8k' }), 'Choose the container: 2K or 4K.');
assert.equal(failure({ ...base, picture: 'imax' }), 'Choose the picture format: flat, scope, HDTV or full.');
assert.equal(failure({ ...base, fps: '' }), 'Enter the frame rate.');
assert.equal(failure({ ...base, fps: '23.976' }), 'Frame rate must be a whole number.');
assert.equal(failure({ ...base, fps: '120' }), 'Choose a frame rate of 24, 25, 30, 48, 50 or 60 fps.');
assert.equal(failure({ ...base, container: '4k', fps: '48' }), 'A 4K container supports 24, 25 or 30 fps.');
assert.equal(failure({ ...base, stereo: true, container: '4k' }), 'A stereoscopic DCP is 2K only.');
assert.equal(failure({ ...base, stereo: true, fps: '30' }), 'A stereoscopic DCP supports 24 or 48 fps.');
assert.equal(failure({ ...base, imageRate: '' }), 'Enter the image bit rate.');
assert.equal(failure({ ...base, imageRate: 'fast' }), 'Image bit rate must be a number.');
assert.equal(failure({ ...base, imageRate: '0' }), 'Image bit rate must be between 1 and 250 Mbit/s.');
assert.equal(failure({ ...base, imageRate: '251' }), 'Image bit rate must be between 1 and 250 Mbit/s.');
assert.equal(failure({ ...base, channels: '' }), 'Enter the audio channel count.');
assert.equal(failure({ ...base, channels: 'six' }), 'Audio channel count must be a whole number.');
assert.equal(failure({ ...base, channels: '0' }), 'Audio channel count must be between 1 and 16.');
assert.equal(failure({ ...base, channels: '17' }), 'Audio channel count must be between 1 and 16.');
assert.equal(failure({ ...base, sampleRate: '44' }), 'Choose a sample rate of 48 or 96 kHz.');
assert.equal(failure({ ...base, drive: '750' }), 'Choose a delivery drive of 250 GB, 500 GB, 1 TB or 2 TB.');
near(C.analyze({ ...base, runtime: ' 2:00:00 ' }).frames, 172800, 'surrounding spaces are ignored');
near(C.analyze({ ...base, imageRate: '187,5' }).bytesPerFrame, 976562.5, 'a comma is a decimal mark');
near(C.analyze({ ...base, runtime: '0:30' }).runtime, 30, 'mm:ss is accepted');

// ---- The independent Python fixture.
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'tests/fixtures/dcp_vectors.json'), 'utf8'));
assert.ok(fixture.vectors.length >= 100, 'fixture size');
assert.equal(fixture.cases.length, 27, 'fixture carries the catalog cases');

const compare = (label, actual, expected) => {
  if (typeof expected === 'number') {
    near(actual, expected, label);
    return;
  }
  assert.equal(actual, expected, label);
};

for (const vector of fixture.vectors) {
  const result = C.analyze(vector.input);
  for (const [key, expected] of Object.entries(vector.expected)) {
    compare(vector.name + ' ' + key, fields[key] ? fields[key](result) : result[key], expected);
  }
}

// ---- The catalog cases, replayed through the documented input shape.
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'frontend/assets/tool-catalog.json'), 'utf8'));
const matches = catalog.tools.filter((tool) => tool.slug === slug);
assert.equal(matches.length, 1, 'slug must exist exactly once');
const entry = matches[0];
assert.equal(entry.name, 'DCP Delivery Planner');
assert.equal(entry.category, 'Video');
assert.equal(entry.subcategory, 'Planning');
assert.equal(entry.risk, 'low');
assert.equal(entry.maturity, 'draft');
assert.equal(entry.reviewedAt, null);
assert.equal(entry.listed, true);
assert.equal(entry.legacyCategory, null);
assert.equal(entry.icon, '\u{1F3AC}');
assert.equal(new Set(entry.tags).size, entry.tags.length, 'duplicate tags');
assert.equal(new Set(entry.aliases).size, entry.aliases.length, 'duplicate aliases');
assert.ok(entry.method.length > 800, 'method must document the model, the limits and the allowances');
assert.equal(entry.sources.length, 2);
assert.ok(entry.sources[0].url.startsWith('https://en.wikipedia.org/wiki/Digital_Cinema_Package'), 'DCP source url');
assert.ok(entry.sources[1].url.startsWith('https://en.wikipedia.org/wiki/Digital_cinema'), 'digital cinema source url');
assert.equal(entry.testCases.length, 27, 'catalog case count');
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'golden').length, 8);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'boundary').length, 4);
assert.equal(entry.testCases.filter((testCase) => testCase.kind === 'validation').length, 15);
assert.equal(JSON.stringify(entry.testCases), JSON.stringify(fixture.cases), 'the catalog cases are the fixture cases');

for (const testCase of entry.testCases) {
  if (testCase.expectedError) {
    assert.equal(failure(testCase.input), testCase.expectedError, testCase.name);
    continue;
  }
  const result = C.analyze(testCase.input);
  for (const [key, expected] of Object.entries(testCase.expected)) {
    compare(testCase.name + ' ' + key, fields[key] ? fields[key](result) : result[key], expected);
  }
}

// ---- Identities that follow from the arithmetic.
const r = C.analyze(base);
near(r.totalBytes, (r.imageBytes + r.audioBytes) * 1.01, 'the package adds a 1% mux allowance', 1e-12);
near(r.imageBytes, r.frames * r.bytesPerFrame, 'the picture is the frame count times the frame budget', 1e-12);
near(r.bytesPerFrame * 8 * r.fps, r.imageRate * 1e6, 'a frame holds bit rate ÷ frame rate', 1e-12);
near(r.ceilingBytesPerFrame * 8 * r.fps, 250e6, 'the ceiling frame budget uses 250 Mbit/s', 1e-12);
near(r.audioBitsPerSecond, r.channels * r.sampleRate * 1000 * 24, '24-bit PCM at the sample rate', 1e-12);
near(r.audioBytes, r.audioBitsPerSecond / 8 * r.frameDuration, 'the sound track spans the presentation', 1e-12);
near(r.effectiveRate, r.totalBytes * 8 / r.frameDuration / 1e6, 'the package rate is bytes over time', 1e-12);
assert.equal(r.packagesPerDrive, Math.floor(r.driveGb * 1e9 / r.totalBytes));
near(r.totalGb * 1e9, r.totalBytes, 'decimal gigabytes', 1e-12);
near(r.frames, r.runtime * r.fps, 'the frame count is the runtime times the rate', 1e-12);
near(r.frameDuration, r.runtime, 'whole-second runtimes land on whole frames', 1e-12);
assert.equal(r.timecode, '02:00:00:00');
near(r.bytesPerFrame, 781250, '150 Mbit/s at 24 fps is 781,250 bytes a frame', 1e-12);
near(r.ceilingBytesPerFrame, 1302083.3333333333, '250 Mbit/s at 24 fps', 1e-12);
near(r.audioBitsPerSecond, 6912000, '5.1 at 48 kHz is 6.912 Mbit/s', 1e-12);
assert.equal(r.packagesPerDrive, 7);

// Doubling the image rate doubles the picture and leaves the sound alone.
const doubled = C.analyze({ ...base, imageRate: '250' });
near(doubled.imageBytes / r.imageBytes, 250 / 150, 'the picture scales with the bit rate', 1e-12);
near(doubled.audioBytes, r.audioBytes, 'the sound track ignores the picture rate', 1e-12);

// Halving the frame rate doubles the frame budget at the same bit rate.
const half = C.analyze({ ...base, fps: '48' });
near(half.bytesPerFrame * 2, r.bytesPerFrame, 'the frame budget is inversely proportional to the rate', 1e-12);
near(half.imageBytes, r.imageBytes, 'the same bit rate and runtime carry the same picture data', 1e-12);

// Container geometry: the active picture sits inside the DCI container.
const scope = C.analyze({ ...base, picture: 'scope' });
assert.equal(scope.bars.axis, 'letterbox');
near(scope.bars.perSide, 111, 'scope in a 2K container leaves 111 px top and bottom', 1e-12);
assert.equal(scope.activeWidth, 2048);
assert.equal(scope.activeHeight, 858);
assert.equal(r.bars.axis, 'pillarbox');
near(r.bars.perSide, 25, 'flat in a 2K container leaves 25 px each side', 1e-12);
const full = C.analyze({ ...base, picture: 'full' });
assert.equal(full.bars.axis, 'none');
assert.equal(full.bars.perSide, 0);
const hdtv4k = C.analyze({ ...base, container: '4k', picture: 'hdtv' });
assert.equal(hdtv4k.activeWidth, 3840);
assert.equal(hdtv4k.activeHeight, 2160);
near(hdtv4k.bars.perSide, 128, 'HDTV in a 4K container leaves 128 px each side', 1e-12);

// Stereoscopic packages share the ceiling between the eyes.
const stereo = C.analyze({ ...base, stereo: true, imageRate: '200' });
assert.equal(stereo.stereo, true);
near(stereo.perEyeRate, 100, 'each eye gets half the image rate', 1e-12);
assert.equal(C.analyze(base).perEyeRate, null);
assert.equal(failure({ ...base, stereo: true, imageRate: '251' }),
  'Image bit rate must be between 1 and 250 Mbit/s.');

// A larger drive holds more packages and a longer feature holds fewer.
assert.ok(C.analyze({ ...base, drive: '2000' }).packagesPerDrive > r.packagesPerDrive,
  'a bigger drive holds more packages');
assert.ok(C.analyze({ ...base, runtime: '4:00:00' }).packagesPerDrive < r.packagesPerDrive,
  'a longer feature fits fewer times');

// ---- Page contract: shared shell, accessible controls, no runtime foreign APIs.
assert.ok(!/fetch\(|XMLHttpRequest|localStorage|sessionStorage|indexedDB|WebSocket/.test(html), 'network or storage API found');
assert.ok(!/<script[^>]+src="https?:/i.test(html), 'remote script');
assert.ok(!/<link[^>]+href="https?:/i.test(html), 'remote stylesheet');
assert.ok(!/on(?:click|input|change|submit)=/i.test(html), 'inline handler');
assert.ok(!/\beval\s*\(|new\s+Function\b/.test(html), 'unsafe script evaluation');
assert.ok(html.includes('<form id="dcp-form" novalidate>'), 'form missing');
assert.ok(html.includes('type="submit"'), 'submit missing');
assert.ok(html.includes('role="alert"'), 'error announcement missing');
assert.ok(html.includes('aria-live="polite" aria-atomic="true"'), 'result region missing');
assert.ok(html.includes('/assets/app.js') && html.includes('/assets/style.css'), 'shared shell assets missing');
for (const id of ['runtime', 'container', 'picture', 'fps', 'image-rate', 'channels', 'sample-rate', 'drive', 'stereo']) {
  assert.ok(html.includes('for="' + id + '"'), 'missing label for ' + id);
  assert.ok(html.includes('id="' + id + '"'), 'missing control ' + id);
}
for (const id of ['dcp-form', 'dcp-err', 'dcp-out', 'note', 'reset', 'submit']) {
  assert.ok(html.includes('id="' + id + '"'), 'missing id ' + id);
}
assert.ok(html.includes('min-height:44px'), 'controls must stay at a 44 px touch target');
assert.ok(/@media \(max-width:360px\)/.test(html), 'small-screen rule missing');
assert.ok(!/style="[^"]*width:\s*\d{3,}px/.test(html), 'fixed wide inline styles');

const publicCount = catalog.tools.filter((tool) => tool.listed).length;
assert.ok(publicCount >= 2068, 'the catalog keeps growing: ' + publicCount);
assert.equal(catalog.tools.filter((tool) => tool.category === 'Video').length, 57, 'Video count');

console.log('dcp-delivery-planner: 27 catalog cases, ' + fixture.vectors.length +
  ' reference vectors, identities and page contracts passed');
