#!/usr/bin/env python3
"""Apply the declarative catalog curation policy without deleting tool pages."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from urllib.parse import urlencode

from generate_tool_catalog import load_catalog, public_tools, write_browser_artifacts
from i18n_lib import load_registry


SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
QUERY_KEY_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")


def render_redirect_config(redirects: dict[str, str], policy: dict, data_dir: Path) -> str:
    queries = policy.get("redirect_queries", {})
    locales = policy.get("redirect_locales", {})
    if not isinstance(queries, dict):
        raise ValueError("tool-curation.json: redirect_queries must be an object")
    if not isinstance(locales, dict) or locales.keys() - redirects.keys():
        raise ValueError("tool-curation.json: redirect_locales must map existing redirect sources")
    locale_paths = {}
    if locales:
        locale_paths = {entry["code"]: entry["path"] for entry in load_registry(data_dir)["locales"]}
    lines = ["# Generated by scripts/apply_tool_curation.py; do not edit manually."]
    for source, target in sorted(redirects.items()):
        if not SLUG_RE.fullmatch(source) or not SLUG_RE.fullmatch(target):
            raise ValueError(f"Invalid redirect slug: {source!r} -> {target!r}")
        params = queries.get(source)
        suffix = ""
        if params is not None:
            if (
                not isinstance(params, dict)
                or not params
                or any(
                    not isinstance(key, str)
                    or not QUERY_KEY_RE.fullmatch(key)
                    or not isinstance(value, str)
                    or not SLUG_RE.fullmatch(value)
                    for key, value in params.items()
                )
            ):
                raise ValueError(f"Invalid redirect query for {source}")
            suffix = "?" + urlencode(sorted(params.items()))

        prefixes = [""]
        endings = ("/",)
        if source in locales:
            # Previously published directories also accepted slashless and index.html URLs.
            endings = ("/", "", "/index.html")
            codes = locales[source]
            if not isinstance(codes, list):
                raise ValueError(f"Invalid redirect locales for {source}")
            for code in codes:
                path = locale_paths.get(code) if isinstance(code, str) else None
                if not path or not SLUG_RE.fullmatch(path) or "/" + path in prefixes:
                    raise ValueError(f"Invalid or duplicate redirect locale for {source}: {code!r}")
                if not (data_dir / "i18n" / "tools" / code / f"{target}.json").is_file():
                    raise ValueError(f"Missing translated redirect target for {source}: {code}/{target}")
                prefixes.append("/" + path)
        for prefix in prefixes:
            destination = f"{prefix}/tools/{target}/{suffix}"
            for ending in endings:
                lines.append(f"location = {prefix}/tools/{source}{ending} {{ return 301 {destination}; }}")
    return "\n".join(lines) + "\n"


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    frontend = root / "frontend"
    policy = json.loads((root / "data" / "tool-curation.json").read_text(encoding="utf-8"))
    risk_policy = json.loads((root / "data" / "tool-risk-policy.json").read_text(encoding="utf-8"))
    generated = json.loads((root / "data" / "generated-conversion-tools.json").read_text(encoding="utf-8"))
    redirects = dict(policy["redirects"])
    redirects.update(generated.get("legacy_redirects", {}))
    try:
        redirect_config = render_redirect_config(redirects, policy, root / "data")
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1

    risk_by_slug: dict[str, str] = {}
    for group in risk_policy.get("groups", []):
        risk = group.get("risk")
        for slug in group.get("slugs", []):
            previous = risk_by_slug.get(slug)
            if previous is not None and previous != risk:
                print(f"tool-risk-policy.json: conflicting risk for {slug}", file=sys.stderr)
                return 1
            risk_by_slug[slug] = risk
    catalog_path = frontend / "assets" / "tool-catalog.json"
    document, tools = load_catalog(catalog_path)

    keep = set(policy["keep"])
    unlisted = set(policy["unlist"]) | set(redirects) | set(risk_by_slug)
    pages = {page.parent.name for page in (frontend / "tools").glob("*/index.html")}
    for slug in pages:
        if any(slug.startswith(item) for item in policy["unlist_prefixes"]) and slug not in keep:
            unlisted.add(slug)

    # Unlisted, quarantined and redirect-source slugs no longer have a page in
    # the repository; the curation data is their only remaining record.
    # Preserve quarantined entries and their review metadata in the canonical
    # catalog, but make the publication decision explicit and durable.
    for tool in tools:
        if tool["slug"] in risk_by_slug:
            tool["risk"] = risk_by_slug[tool["slug"]]
        if tool["slug"] in unlisted:
            tool["listed"] = False
    document["tools"] = tools
    catalog_path.write_text(
        json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    write_browser_artifacts(frontend, public_tools(tools, unlisted))

    (root / "nginx").mkdir(exist_ok=True)
    (root / "nginx" / "tool-redirects.conf").write_text(
        redirect_config, encoding="utf-8"
    )
    print(f"Unlisted {len(unlisted)} curated slugs; generated {len(redirects)} redirects")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
