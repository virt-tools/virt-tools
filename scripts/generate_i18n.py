#!/usr/bin/env python3
"""Build the locale bundles and the localized page tree for virt-tools.

Two artifacts come out of this script:

  frontend/assets/i18n/<code>.js   runtime message bundle (committed, like tools.js)
  <root>/<path>/**                 localized page copies (build output only)

A tool page is published for a locale only when its translation memory exists and
is complete *and* still matches the English page it was translated from. Anything
else falls back to English, which is the only honest option while the catalog
grows by roughly twenty pages a day.

Usage:
  generate_i18n.py <root>            render bundles and locale pages into <root>
  generate_i18n.py --check           verify data + committed bundles, write nothing
  generate_i18n.py <root> --bundles-only
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import i18n_lib

SHELL_HEADER = "/* Generated by scripts/generate_i18n.py; do not edit. */\n"


class Report:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.warnings: list[str] = []

    def error(self, message: str) -> None:
        self.errors.append(message)

    def warn(self, message: str) -> None:
        self.warnings.append(message)


def project_root(root: Path) -> Path:
    return root.parent if (root.parent / "data").is_dir() else Path.cwd()


def load_catalogs(data_dir: Path, registry: dict, report: Report) -> dict[str, dict]:
    catalogues: dict[str, dict] = {}
    for entry in registry["locales"]:
        path = data_dir / "i18n" / "messages" / f"{entry['code']}.json"
        if not path.is_file():
            report.error(f"missing message catalog: {path.relative_to(data_dir.parent)}")
            continue
        try:
            catalogues[entry["code"]] = i18n_lib.load_json(path)
        except json.JSONDecodeError as exc:
            report.error(f"{path.relative_to(data_dir.parent)}: {exc}")
    return catalogues


def validate_catalogs(registry: dict, catalogues: dict[str, dict], report: Report) -> None:
    default = registry["default"]
    base = catalogues.get(default, {})
    if not base:
        report.error(f"default locale {default} has no message catalog")
        return
    base_messages = base.get("messages", {})
    base_categories = base.get("categories", {})
    base_groups = base.get("groups", {})
    if not base_messages:
        report.error(f"default locale {default} has no messages")
    for entry in registry["locales"]:
        code = entry["code"]
        catalog = catalogues.get(code)
        if not catalog:
            continue
        if catalog.get("locale") != code:
            report.error(f"messages/{code}.json declares locale {catalog.get('locale')!r}")
        if catalog.get("dir", entry.get("dir", "ltr")) != entry.get("dir", "ltr"):
            report.error(f"messages/{code}.json dir disagrees with the registry")
        messages = catalog.get("messages", {})
        missing = sorted(set(base_messages) - set(messages))
        extra = sorted(set(messages) - set(base_messages))
        if code != default and missing:
            report.error(f"messages/{code}.json is missing {len(missing)} keys: {', '.join(missing[:6])}")
        if extra:
            report.error(f"messages/{code}.json has unknown keys: {', '.join(extra[:6])}")
        for message_key, value in messages.items():
            if not isinstance(value, str) or not value.strip():
                report.error(f"messages/{code}.json: {message_key} is empty")
        for field, reference in (("categories", base_categories), ("groups", base_groups)):
            provided = catalog.get(field, {})
            absent = sorted(set(reference) - set(provided))
            if code != default and absent:
                report.error(f"messages/{code}.json {field} is missing: {', '.join(absent[:6])}")
            unknown = sorted(set(provided) - set(reference))
            if unknown:
                report.error(f"messages/{code}.json {field} has unknown entries: {', '.join(unknown[:6])}")


def tm_path(data_dir: Path, code: str, slug: str) -> Path:
    return data_dir / "i18n" / "tools" / code / f"{slug}.json"


def load_tm(data_dir: Path, code: str, slug: str) -> dict | None:
    path = tm_path(data_dir, code, slug)
    if not path.is_file():
        return None
    return i18n_lib.load_json(path)


def verify_tm(tm: dict, slug: str, locale: str, document: dict) -> list[str]:
    """Return the problems that stop this translation from being published."""
    problems: list[str] = []
    if tm.get("slug") != slug:
        problems.append(f"slug mismatch ({tm.get('slug')!r})")
    if tm.get("locale") != locale:
        problems.append(f"locale mismatch ({tm.get('locale')!r})")
    strings = tm.get("strings")
    if not isinstance(strings, dict) or not strings:
        return problems + ["no strings block"]
    empty = sorted(key for key, value in strings.items() if not isinstance(value, str) or not value.strip())
    if empty:
        problems.append(f"{len(empty)} empty translations, first: {empty[0][:60]!r}")
    current = set(i18n_lib.units(document))
    missing = sorted(current - set(strings))
    orphan = sorted(set(strings) - current)
    if missing:
        problems.append(f"{len(missing)} untranslated strings, first: {missing[0][:60]!r}")
    if orphan:
        problems.append(f"{len(orphan)} stale strings no longer on the page, first: {orphan[0][:60]!r}")
    expected = i18n_lib.source_hash(document)
    if tm.get("sourceHash") != expected:
        problems.append(f"source hash drift ({str(tm.get('sourceHash'))[:18]}… != {expected[:18]}…)")
    return problems


def bundle_payload(entry: dict, catalog: dict, tools: dict[str, dict], coverage: dict[str, list[str]]) -> dict:
    return {
        "code": entry["code"],
        "name": entry.get("name", entry["code"]),
        "dir": entry.get("dir", "ltr"),
        "path": entry.get("path", ""),
        "htmlLang": entry.get("htmlLang", entry["code"]),
        "messages": catalog.get("messages", {}),
        "categories": catalog.get("categories", {}),
        "groups": catalog.get("groups", {}),
        "tools": tools,
        # Which slugs exist in each locale, so the shell can link a translated
        # page and fall back to the English one for everything else.
        "catalog": coverage,
    }


def read_app_tables(root: Path, report: Report) -> tuple[dict, list]:
    """Read the shell's English defaults and locale directory out of app.js.

    The runtime needs both without an extra request, so they live in app.js; this
    gate is what keeps that copy honest against data/i18n/.
    """
    path = root / "assets" / "app.js"
    if not path.is_file():
        report.error(f"missing shell script: {path}")
        return {}, []
    text = path.read_text(encoding="utf-8")
    english_match = re.search(r"var VT_EN = (\{.*?\n  \});", text, re.S)
    locales_match = re.search(r"var LOCALES = (\[.*?\]);", text, re.S)
    if not english_match:
        report.error("app.js: cannot locate the VT_EN table")
        return {}, []
    if not locales_match:
        report.error("app.js: cannot locate the LOCALES directory")
        return {}, []
    try:
        english = json.loads(english_match.group(1))
    except json.JSONDecodeError as exc:
        report.error(f"app.js: VT_EN is not valid JSON ({exc})")
        return {}, []
    try:
        locales = json.loads(locales_match.group(1))
    except json.JSONDecodeError as exc:
        report.error(f"app.js: LOCALES is not valid JSON ({exc})")
        return [], []
    return english, locales


def verify_app_tables(english: dict, locales: list[dict], registry: dict, catalogues: dict[str, dict], report: Report) -> None:
    base = catalogues.get(registry["default"], {}).get("messages", {})
    if not base:
        return
    missing = sorted(set(base) - set(english))
    extra = sorted(set(english) - set(base))
    if missing:
        report.error(f"app.js VT_EN is missing keys: {', '.join(missing[:6])}")
    if extra:
        report.error(f"app.js VT_EN has keys absent from messages/en.json: {', '.join(extra[:6])}")
    for key in sorted(set(base) & set(english)):
        if base[key] != english[key]:
            report.error(f"app.js VT_EN[{key}] disagrees with messages/en.json")
    shell = [(item.get("code"), item.get("path", "")) for item in locales]
    registered = [(item["code"], item.get("path", "")) for item in registry["locales"]]
    if shell != registered:
        report.error(
            "app.js LOCALES disagrees with data/i18n/locales.json "
            f"(app.js {shell} vs registry {registered})"
        )


def bundle_text(payload: dict) -> str:
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    return SHELL_HEADER + "window.VT_I18N = " + body + ";\n"


PAGE_MESSAGES = {
    # English source text of the homepage shell -> message key. The page is
    # static markup, so the build has to map its literals onto catalog keys.
    "Browser tools": "home.eyebrow",
    "All tools": "home.title",
    "Private utilities that run on your device. No accounts, no uploads, no tracking.": "home.lede",
    "Search tools": "home.searchLabel",
    "Filter by category": "home.chipsLabel",
    "Saved": "home.saved",
    "Sort": "home.sortLabel",
    "Sort order": "home.sortGroup",
    "A–Z": "home.sortAz",
    "Recent": "home.sortRecent",
    "No tools match your search.": "home.emptyDefault",
    "Show more tools": "home.loadMore",
    "JavaScript is required to search and browse the catalog.": "home.noscript",
}


def shell_mapping(messages_en: dict, messages_loc: dict) -> dict[str, str]:
    mapping = {}
    for english, key in PAGE_MESSAGES.items():
        target = messages_loc.get(key)
        if target and target != english:
            mapping[english] = target
    return mapping


def absolutize(text: str) -> str:
    """Rewrite homepage-relative asset URLs so a copy at /<locale>/ still resolves."""
    for attr in ('href="assets/', 'src="assets/'):
        text = text.replace(attr, attr.replace('"assets/', '"/assets/'))
    return text


def set_lang(text: str, html_lang: str, direction: str) -> str:
    marker = '<html lang="en">'
    if marker in text:
        text = text.replace(marker, f'<html lang="{html_lang}" dir="{direction}">', 1)
    else:
        text = text.replace("<html>", f'<html lang="{html_lang}" dir="{direction}">', 1)
    return text


def inject_bundle(text: str, code: str) -> str:
    tag = f'<script src="/assets/i18n/{code}.js"></script>'
    if tag in text:
        return text
    for needle in ('<script src="/assets/app.js"></script>', '<script src="assets/app.js"></script>'):
        if needle in text:
            return text.replace(needle, tag + "\n  " + needle, 1)
    return text


def render_homepage(root: Path, entry: dict, mapping: dict, report: Report) -> str | None:
    source_path = root / "index.html"
    if not source_path.is_file():
        report.error(f"missing homepage: {source_path}")
        return None
    text = source_path.read_text(encoding="utf-8")
    rendered, applied, unused = i18n_lib.render(text, mapping)
    if unused:
        report.warn(f"homepage/{entry['code']}: {len(unused)} catalog strings not present in the markup")
    rendered = absolutize(set_lang(rendered, entry.get("htmlLang", entry["code"]), entry.get("dir", "ltr")))
    return inject_bundle(rendered, entry["code"])


def main(argv: list[str]) -> int:
    check = "--check" in argv
    bundles_only = "--bundles-only" in argv
    positional = [arg for arg in argv[1:] if not arg.startswith("--")]
    root = Path(positional[0]) if positional else Path("frontend")
    if not root.is_absolute():
        root = (Path.cwd() / root).resolve()

    data_dir = project_root(root) / "data"
    report = Report()
    registry = i18n_lib.load_registry(data_dir)
    catalogues = load_catalogs(data_dir, registry, report)
    validate_catalogs(registry, catalogues, report)

    default_code = registry["default"]
    base_units = catalogues.get(default_code, {}).get("messages", {})

    # Translation memories drive the per-locale tool coverage.
    tool_documents: dict[str, dict] = {}
    for page in sorted((root / "tools").glob("*/index.html")):
        tool_documents[page.parent.name] = i18n_lib.extract_units(
            i18n_lib.parse(page.read_text(encoding="utf-8"))[0]
        )

    locale_state: dict[str, dict] = {}
    for entry in registry["locales"]:
        code = entry["code"]
        catalog = catalogues.get(code, {})
        published: dict[str, dict] = {}
        if code != default_code:
            for slug in sorted(tool_documents):
                tm = load_tm(data_dir, code, slug)
                if not tm:
                    continue
                problems = verify_tm(tm, slug, code, tool_documents[slug])
                if problems:
                    report.warn(f"{code}/{slug}: not published — {problems[0]}")
                    continue
                published[slug] = tm
        locale_state[code] = {"entry": entry, "catalog": catalog, "published": published}

    coverage = {
        entry["code"]: sorted(locale_state[entry["code"]]["published"])
        for entry in registry["locales"]
        if entry["code"] != default_code
    }

    if check:
        english_table, shell_locales = read_app_tables(root, report)
        verify_app_tables(english_table, shell_locales, registry, catalogues, report)
        bundle_dir = root / "assets" / "i18n"
        for entry in registry["locales"]:
            code = entry["code"]
            if code == default_code:
                continue
            state = locale_state[code]
            tools = {
                slug: {"name": tm.get("name", ""), "description": tm.get("description", "")}
                for slug, tm in state["published"].items()
                if tm.get("name") and tm.get("description")
            }
            expected = bundle_text(bundle_payload(entry, state["catalog"], tools, coverage))
            target = bundle_dir / f"{code}.js"
            if not target.is_file():
                report.error(f"missing bundle {target.relative_to(root)} (run scripts/generate_i18n.py)")
            elif target.read_text(encoding="utf-8") != expected:
                report.error(f"stale bundle {target.relative_to(root)} (run scripts/generate_i18n.py)")
        for line in report.errors:
            print("error: " + line, file=sys.stderr)
        if report.errors:
            return 1
        for line in report.warnings:
            print("note: " + line, file=sys.stderr)
        published_total = sum(len(state["published"]) for code, state in locale_state.items() if code != default_code)
        print(
            f"i18n data current: {len(registry['locales'])} locales, "
            f"{published_total} localized tool pages, {len(tool_documents)} source pages"
        )
        return 0

    # ---- bundles -----------------------------------------------------------
    bundle_dir = root / "assets" / "i18n"
    bundle_dir.mkdir(parents=True, exist_ok=True)
    written_bundles = []
    for entry in registry["locales"]:
        code = entry["code"]
        if code == default_code:
            continue
        state = locale_state[code]
        tools = {
            slug: {"name": tm.get("name", ""), "description": tm.get("description", "")}
            for slug, tm in state["published"].items()
            if tm.get("name") and tm.get("description")
        }
        payload = bundle_payload(entry, state["catalog"], tools, coverage)
        target = bundle_dir / f"{code}.js"
        target.write_text(bundle_text(payload), encoding="utf-8")
        written_bundles.append(f"{code}.js ({len(tools)} tools)")

    manifest: dict[str, dict] = {}
    if not bundles_only:
        curation_path = data_dir / "tool-curation.json"
        curation = i18n_lib.load_json(curation_path) if curation_path.is_file() else {}
        retired_locales = curation.get("redirect_locales", {})
        for entry in registry["locales"]:
            code = entry["code"]
            path = entry.get("path", "")
            if code == default_code or not path:
                continue
            state = locale_state[code]
            locale_root = root / path
            homepage = render_homepage(root, entry, shell_mapping(base_units, state["catalog"].get("messages", {})), report)
            if homepage is None:
                continue
            locale_root.mkdir(parents=True, exist_ok=True)
            (locale_root / "index.html").write_text(homepage, encoding="utf-8")
            # An incremental build may still contain the retired tool's translated HTML.
            for page in (locale_root / "tools").glob("*/index.html"):
                slug = page.parent.name
                if slug not in tool_documents and code in retired_locales.get(slug, ()):
                    page.unlink()
            messages = state["catalog"].get("messages", {})
            pages = {
                "": {
                    "name": messages.get("home.metaTitle", ""),
                    "description": messages.get("home.metaDescription", ""),
                }
            }
            for slug, tm in sorted(state["published"].items()):
                source = (root / "tools" / slug / "index.html").read_text(encoding="utf-8")
                rendered, applied, unused = i18n_lib.render(source, tm["strings"])
                if unused:
                    report.error(f"{code}/{slug}: {len(unused)} translations unused after render")
                    continue
                rendered = set_lang(rendered, entry.get("htmlLang", code), entry.get("dir", "ltr"))
                rendered = inject_bundle(rendered, code)
                target = locale_root / "tools" / slug / "index.html"
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(rendered, encoding="utf-8")
                pages[f"tools/{slug}/"] = {
                    "name": tm.get("name", ""),
                    "description": tm.get("description", ""),
                }
                if tm.get("guidance"):
                    pages[f"tools/{slug}/"]["guidance"] = tm["guidance"]
            manifest[code] = {
                "path": path,
                "htmlLang": entry.get("htmlLang", code),
                "pages": pages,
            }
        (root / "assets" / "i18n" / "manifest.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )

    for line in report.errors:
        print("error: " + line, file=sys.stderr)
    if report.errors:
        return 1
    for line in report.warnings:
        print("note: " + line, file=sys.stderr)
    print("Wrote bundles: " + ", ".join(written_bundles))
    if not bundles_only:
        for code, state in manifest.items():
            print(f"  {code}: {len(state['pages'])} pages ({len(state['pages']) - 1} tools + homepage)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
