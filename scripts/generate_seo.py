#!/usr/bin/env python3
"""Inject SEO and trust metadata into the homepage and public tool pages.

The canonical JSON catalog is the single source of truth for per-tool metadata.
This script rewrites the built HTML in place so the nginx
image serves fully-formed meta tags with no runtime logic.

Usage: generate_seo.py <frontend_root> <base_url>
  <frontend_root>  path to the frontend/ directory (e.g. frontend)
  <base_url>      absolute site URL without trailing slash (e.g. https://virt.tools)

It inserts a block immediately before `</head>` in:
  - <frontend_root>/index.html            (homepage: WebSite + SearchAction)
  - <frontend_root>/tools/<slug>/index.html (per tool: WebApplication)

Tool pages also get two static internal-link blocks in the body: a breadcrumb
(`All tools` -> the page's own locale home, then the tool itself as the current
crumb) and a related-tools list of up to eight sibling tools from the same
catalog category. The runtime shell builds both in the browser, which leaves the
raw HTML without a single `<a href="/tools/...">`; see the "Build-time internal
links" section below.

It also adds a per-page `Content-Security-Policy` meta element that pins every
inline script and inline event handler by SHA-256 hash, so browsers that support
hashes reject script that was not present at build time.

Idempotent: any previously injected block (delimited by SEO/CSP/NAV/RELATED
BEGIN/END comments) is removed before re-inserting, so re-runs don't accumulate.
"""
import html
import base64
import hashlib
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

try:
    from .generate_tool_catalog import public_guidance
except ImportError:  # Direct script execution places scripts/ on sys.path.
    from generate_tool_catalog import public_guidance

SITE_NAME = "Virtual Tools"
HOME_DESC = "A collection of free browser-based tools that run locally and preserve your privacy."
OG_IMAGE = "/assets/og-image.png"
OG_IMAGE_ALT = "Virtual Tools — free, private, browser-based utilities"
BEGIN = "<!-- SEO BEGIN (generated by scripts/generate_seo.py; do not edit) -->"
END = "<!-- SEO END -->"

BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.DOTALL)


def esc_attr(s: str) -> str:
    """Escape a value for use inside an HTML attribute."""
    return html.escape(s or "", quote=True)


def jsonld(obj) -> str:
    """Serialise JSON-LD, escaping characters that could break the <script> context."""
    s = json.dumps(obj, ensure_ascii=False)
    return s.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


def load_manifest(root: Path) -> dict:
    """Locale pages written by generate_i18n.py (empty for an English-only build)."""
    path = root / "assets" / "i18n" / "manifest.json"
    if not path.is_file():
        return {}
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return manifest if isinstance(manifest, dict) else {}


def alternate_block(base: str, relative: str, manifest: dict) -> list[tuple[str, str]]:
    """(hreflang, url) pairs for one page path across every published locale.

    `relative` is "" for the homepage or "tools/<slug>/". English is always the
    x-default because it is the only locale that covers the whole catalog.
    """
    pairs: list[tuple[str, str]] = [("x-default", base + "/" + relative), ("en", base + "/" + relative)]
    for code, info in sorted(manifest.items()):
        if relative not in info.get("pages", {}):
            continue
        pairs.append((code, base + "/" + info["path"] + "/" + relative))
    return pairs


def hreflang_tags(pairs: list[tuple[str, str]]) -> str:
    if len({url for _, url in pairs}) < 2:
        return ""
    return "".join(
        f'  <link rel="alternate" hreflang="{esc_attr(code)}" href="{esc_attr(url)}">\n'
        for code, url in pairs
    )


def load_catalog(root: Path) -> list[dict]:
    """Load public entries and apply curation as a final publication guard."""
    document = json.loads((root / "assets" / "tool-catalog.json").read_text(encoding="utf-8"))
    tools = document.get("tools")
    if not isinstance(tools, list):
        raise RuntimeError("canonical catalog has no tools array")
    project_root = root.parent
    hidden: set[str] = set()
    policy_path = project_root / "data" / "tool-curation.json"
    if policy_path.is_file():
        policy = json.loads(policy_path.read_text(encoding="utf-8"))
        keep = set(policy.get("keep", []))
        hidden.update(policy.get("unlist", []))
        hidden.update(policy.get("redirects", {}))
        prefixes = tuple(policy.get("unlist_prefixes", []))
        if prefixes:
            hidden.update(
                page.parent.name
                for page in (root / "tools").glob("*/index.html")
                if page.parent.name.startswith(prefixes) and page.parent.name not in keep
            )
        hidden.difference_update(keep)
    generated_path = project_root / "data" / "generated-conversion-tools.json"
    if generated_path.is_file():
        generated = json.loads(generated_path.read_text(encoding="utf-8"))
        hidden.update(generated.get("legacy_redirects", {}))
    return [
        tool for tool in tools
        if isinstance(tool, dict) and tool.get("listed", True) and tool.get("slug") not in hidden
    ]


def meta_tags(*triples: tuple[str, str, str | None]) -> str:
    # Each triple is (attr_name, attr_value, content) e.g. ("name", "description", "...").
    return "\n".join(
        f'  <meta {a}="{esc_attr(k)}" content="{esc_attr(c)}">'
        for a, k, c in triples if c is not None
    )


def inject(path: Path, block: str) -> None:
    html_text = path.read_text(encoding="utf-8")
    html_text = BLOCK_RE.sub("", html_text)
    # Become the sole owner of the description meta (tool pages have none; the
    # homepage has a hand-written one) so we never emit a duplicate.
    html_text = re.sub(r'[ \t]*<meta\s+name="description"[^>]*>\n?', "", html_text)
    if "</head>" not in html_text:
        raise RuntimeError(f"{path}: no </head> to inject before")
    html_text = html_text.replace("</head>", block + "\n</head>", 1)
    path.write_text(html_text, encoding="utf-8")


# ---------------------------------------------------------------------------
# Build-time internal links
#
# assets/app.js builds the catalog, the breadcrumb and the related-tools list in
# the browser, so the shipped HTML of a tool page contains no <a href="/tools/">
# at all and every page is reachable only through the sitemaps. These blocks are
# static markup: no <script>, no event handler, no style attribute, so the CSP
# hash pass below sees exactly the inline code it saw before.
# ---------------------------------------------------------------------------

NAV_BEGIN = "<!-- SEO-NAV BEGIN (generated by scripts/generate_seo.py; do not edit) -->"
NAV_END = "<!-- SEO-NAV END -->"
RELATED_BEGIN = "<!-- SEO-RELATED BEGIN (generated by scripts/generate_seo.py; do not edit) -->"
RELATED_END = "<!-- SEO-RELATED END -->"

NAV_BLOCK_RE = re.compile(
    r"\n?[ \t]*" + re.escape(NAV_BEGIN) + r".*?" + re.escape(NAV_END) + r"[ \t]*\n?",
    re.DOTALL,
)
RELATED_BLOCK_RE = re.compile(
    r"\n?[ \t]*" + re.escape(RELATED_BEGIN) + r".*?" + re.escape(RELATED_END) + r"[ \t]*\n?",
    re.DOTALL,
)

# Build-time chrome, not page copy: scripts/i18n_lib.py only extracts the source
# pages, so these labels never enter the translation pipeline and need no memory
# entry. Wording follows the locale's own homepage heading ("All tools").
LINK_CHROME: dict[str, dict[str, str]] = {
    "en": {"breadcrumb": "Breadcrumb", "allTools": "All tools", "related": "Related tools"},
    "de": {"breadcrumb": "Pfadnavigation", "allTools": "Alle Tools", "related": "Ähnliche Tools"},
    "es": {
        "breadcrumb": "Ruta de navegación",
        "allTools": "Todas las herramientas",
        "related": "Herramientas relacionadas",
    },
}
DEFAULT_CHROME = LINK_CHROME["en"]
RELATED_LIMIT = 8

# Elements whose text is not markup: a sample document in a <textarea> or a tag
# built inside a <script> string must never be mistaken for the real <main>.
_PROTECTED_RE = re.compile(
    r"<(script|style|textarea|template|pre)\b[^>]*>(.*?)</\1\s*>",
    re.IGNORECASE | re.DOTALL,
)


def _protected_ranges(text: str) -> list[tuple[int, int]]:
    """(start, end) spans of element content that only looks like markup."""
    return [(match.start(2), match.end(2)) for match in _PROTECTED_RE.finditer(text)]


def _find_tag(text: str, pattern: str, ranges: list[tuple[int, int]],
              start: int = 0) -> tuple[int, int] | None:
    """First `pattern` match outside protected ranges, as absolute offsets."""
    for match in re.finditer(pattern, text[start:], re.IGNORECASE):
        begin = start + match.start()
        if any(low <= begin < high for low, high in ranges):
            continue
        return begin, start + match.end()
    return None


def locale_home(locale_path: str) -> str:
    """Root-relative home URL of a locale tree: "/", "/de/" or "/es/"."""
    prefix = locale_path.strip("/")
    return "/" + prefix + "/" if prefix else "/"


def chrome_for(code: str) -> dict[str, str]:
    return LINK_CHROME.get(code, DEFAULT_CHROME)


def breadcrumb_html(name: str, locale_path: str, code: str) -> str:
    labels = chrome_for(code)
    return (
        NAV_BEGIN + "\n"
        '<nav class="seo-breadcrumb" aria-label="' + esc_attr(labels["breadcrumb"]) + '">\n'
        "  <ol>\n"
        '    <li><a href="' + esc_attr(locale_home(locale_path)) + '">'
        + html.escape(labels["allTools"]) + "</a></li>\n"
        '    <li><span aria-current="page">' + html.escape(name) + "</span></li>\n"
        "  </ol>\n"
        "</nav>\n"
        + NAV_END
    )


def related_links(slug: str, category: str, by_category: dict[str, list[dict]],
                  published: set[str], locale_names: dict[str, str],
                  locale_path: str) -> list[tuple[str, str]]:
    """Up to eight siblings from the same category, in catalog order.

    The window starts after the current tool and wraps around the category, so
    every page links onward to its successors and every tool collects inbound
    links from its predecessors — a plain "first eight of the category" list
    would point the whole category at the same handful of pages and leave the
    rest as orphans again.

    `published` holds the slugs this locale really ships, so a translated tool
    is linked on its locale copy and every other sibling falls back to English.
    Small categories simply yield fewer links.
    """
    records = by_category.get(category, [])
    position = next((index for index, record in enumerate(records)
                     if record.get("slug") == slug), -1)
    if position >= 0:
        records = records[position + 1:] + records[:position + 1]
    links: list[tuple[str, str]] = []
    for other in records:
        other_slug = other.get("slug")
        if not other_slug or other_slug == slug:
            continue
        if locale_path and other_slug in published:
            href = "/" + locale_path.strip("/") + "/tools/" + other_slug + "/"
            label = locale_names.get(other_slug) or other.get("name") or other_slug
        else:
            href = "/tools/" + other_slug + "/"
            label = other.get("name") or other_slug
        links.append((href, label))
        if len(links) == RELATED_LIMIT:
            break
    return links


def related_html(links: list[tuple[str, str]], code: str) -> str | None:
    if not links:
        return None
    labels = chrome_for(code)
    items = "".join(
        '    <li><a href="' + esc_attr(href) + '">' + html.escape(label) + "</a></li>\n"
        for href, label in links
    )
    return (
        RELATED_BEGIN + "\n"
        '<section class="related-tools seo-related" aria-labelledby="seo-related-title">\n'
        '  <h2 id="seo-related-title">' + html.escape(labels["related"]) + "</h2>\n"
        "  <ul>\n" + items + "  </ul>\n"
        "</section>\n"
        + RELATED_END
    )


def inject_tool_links(page: Path, nav: str, related: str | None) -> None:
    """Rewrite one tool page with its breadcrumb and related-tools blocks."""
    text = page.read_text(encoding="utf-8")
    text = NAV_BLOCK_RE.sub("", text)
    text = RELATED_BLOCK_RE.sub("", text)

    ranges = _protected_ranges(text)
    anchor = _find_tag(text, r"<main\b[^>]*>", ranges)
    if anchor is None:
        anchor = _find_tag(text, r"<body\b[^>]*>", ranges)
    if anchor is None:
        raise RuntimeError(f"{page}: no <main> or <body> to inject the breadcrumb into")
    # The breadcrumb opens the page content, ahead of the first heading.
    text = text[:anchor[1]] + "\n" + nav + "\n" + text[anchor[1]:]

    if related:
        ranges = _protected_ranges(text)
        anchor = _find_tag(text, r"</main\s*>", ranges, start=anchor[1])
        if anchor is None:
            # A handful of hand-written pages never closed <main>; the shell
            # script that follows the content is the next best anchor.
            anchor = _find_tag(text, r"""<script\b[^>]*src=["']/assets/app\.js["']""", ranges)
        if anchor is None:
            anchor = _find_tag(text, r"</body\s*>", ranges)
        if anchor is None:
            raise RuntimeError(f"{page}: no anchor for the related-tools section")
        text = text[:anchor[0]] + "\n" + related + "\n" + text[anchor[0]:]

    page.write_text(text, encoding="utf-8")


def homepage_block(base: str, alternates: str = "", title: str = SITE_NAME, desc: str = HOME_DESC,
                   lang: str = "en", url: str | None = None) -> str:
    url = url or base + "/"
    tags = meta_tags(
        ("name", "description", desc),
        ("property", "og:title", title),
        ("property", "og:description", desc),
        ("property", "og:type", "website"),
        ("property", "og:url", url),
        ("property", "og:site_name", SITE_NAME),
        ("property", "og:locale", lang),
        ("property", "og:image", base + OG_IMAGE),
        ("property", "og:image:width", "1200"),
        ("property", "og:image:height", "630"),
        ("property", "og:image:alt", OG_IMAGE_ALT),
        ("name", "twitter:card", "summary_large_image"),
        ("name", "twitter:title", title),
        ("name", "twitter:description", desc),
        ("name", "twitter:image", base + OG_IMAGE),
    )
    ld = jsonld({
        "@context": "https://schema.org",
        "@type": "WebSite",
        "name": SITE_NAME,
        "url": url,
        "inLanguage": lang,
        "potentialAction": {
            "@type": "SearchAction",
            "target": {
                "@type": "EntryPoint",
                "urlTemplate": base + "/?q={search_term_string}",
            },
            "query-input": "required name=search_term_string",
        },
    })
    return (
        BEGIN
        + "\n  <link rel=\"canonical\" href=\"" + esc_attr(url) + "\">\n"
        + alternates
        + tags + "\n"
        + f'  <script type="application/ld+json">{ld}</script>\n'
        + END
    )


def tool_block(base: str, t: dict, alternates: str = "", name: str | None = None,
               desc: str | None = None, url: str | None = None, lang: str = "en",
               guidance: str | None = None) -> str:
    slug = t["slug"]
    url = url or base + "/tools/" + slug + "/"
    name = name or t.get("name", slug)
    desc = desc or t.get("description", name)
    tags = meta_tags(
        ("name", "description", desc),
        ("property", "og:title", name + " — " + SITE_NAME),
        ("property", "og:description", desc),
        ("property", "og:type", "website"),
        ("property", "og:url", url),
        ("property", "og:site_name", SITE_NAME),
        ("property", "og:locale", lang),
        ("property", "og:image", base + OG_IMAGE),
        ("property", "og:image:width", "1200"),
        ("property", "og:image:height", "630"),
        ("property", "og:image:alt", name + " — " + SITE_NAME),
        ("name", "twitter:card", "summary_large_image"),
        ("name", "twitter:title", name + " — " + SITE_NAME),
        ("name", "twitter:description", desc),
        ("name", "twitter:image", base + OG_IMAGE),
        ("name", "vt:tool-slug", slug),
        ("name", "vt:guidance", guidance if guidance else public_guidance(t)),
        ("name", "vt:maturity", t.get("maturity", "unreviewed")),
        ("name", "vt:reviewed-at", t.get("reviewedAt") or ""),
        ("name", "vt:method", t.get("method") or ""),
        ("name", "vt:source-count", str(len(t.get("sources") or []))),
        ("name", "vt:test-count", str(len(t.get("testCases") or []))),
    )
    ld = jsonld({
        "@context": "https://schema.org",
        "@type": "WebApplication",
        "name": name,
        "url": url,
        "description": desc,
        "inLanguage": lang,
        "applicationCategory": t.get("category", "Utility") + "Application",
        "operatingSystem": "Any (web browser)",
        "browserRequirements": "Requires JavaScript",
        "isAccessibleForFree": True,
        "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
    })
    return (
        BEGIN
        + "\n  <link rel=\"canonical\" href=\"" + esc_attr(url) + "\">\n"
        + alternates
        + tags + "\n"
        + f'  <script type="application/ld+json">{ld}</script>\n'
        + END
    )


CSP_BEGIN = "<!-- CSP BEGIN (generated by scripts/generate_seo.py; do not edit) -->"
CSP_END = "<!-- CSP END -->"
CSP_BLOCK_RE = re.compile(
    r"\n[ \t]*" + re.escape(CSP_BEGIN) + r".*?" + re.escape(CSP_END), re.DOTALL
)
JS_TYPES = {
    "",
    "text/javascript",
    "application/javascript",
    "application/x-javascript",
    "text/ecmascript",
    "application/ecmascript",
    "module",
}

# Pages that build markup strings containing event handlers (innerHTML with
# onclick="...") cannot be covered by attribute hashes, because the handler text
# is only known at runtime. They keep 'unsafe-inline' for attributes while their
# inline scripts stay hash-pinned.
DYNAMIC_HANDLER_RE = re.compile(
    r"on(?:click|change|input|keydown|keyup|focus|blur|submit|mouseover|mouseout|error|load)"
    r"\s*=\s*[\"'`\\]",
    re.IGNORECASE,
)


def _source_hash(value: str) -> str:
    # HTML tokenizers replace NUL with U+FFFD before a script executes, so the
    # hash must cover the tokenized text rather than the raw bytes on disk.
    digest = hashlib.sha256(value.replace("\x00", "\ufffd").encode("utf-8")).digest()
    return "'sha256-" + base64.b64encode(digest).decode("ascii") + "'"


class _InlinePolicyCollector(HTMLParser):
    """Collect hashes for inline scripts and inline event-handler attributes.

    HTMLParser decodes character references in attributes and keeps script
    content as raw text, which matches the byte sequence a browser hashes.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.script_hashes: list[str] = []
        self.attribute_hashes: list[str] = []
        self.dynamic_handlers = False
        self._collecting: list[str] | None = None
        self._script_type = ""

    def _start(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        for name, value in attrs:
            if name.lower().startswith("on") and value:
                self.attribute_hashes.append(_source_hash(value))
        if tag.lower() == "script":
            values = {name.lower(): (value or "") for name, value in attrs}
            if "src" not in values:
                self._collecting = []
                self._script_type = values.get("type", "").strip().lower()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self._start(tag, attrs)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self._start(tag, attrs)

    def handle_data(self, data: str) -> None:
        if self._collecting is not None:
            self._collecting.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag.lower() != "script" or self._collecting is None:
            return
        body = "".join(self._collecting)
        if self._script_type in JS_TYPES:
            if DYNAMIC_HANDLER_RE.search(body):
                self.dynamic_handlers = True
            if body.strip():
                self.script_hashes.append(_source_hash(body))
        self._collecting = None


def csp_block(text: str) -> str:
    collector = _InlinePolicyCollector()
    collector.feed(text)
    collector.close()
    script_src = "'self' 'wasm-unsafe-eval'"
    if collector.script_hashes:
        script_src += " " + " ".join(collector.script_hashes)
    if collector.dynamic_handlers:
        script_src_attr = "'unsafe-inline'"
    elif collector.attribute_hashes:
        script_src_attr = "'unsafe-hashes' " + " ".join(collector.attribute_hashes)
    else:
        script_src_attr = "'none'"
    content = f"script-src {script_src}; script-src-attr {script_src_attr}"
    attribute = content.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")
    return (
        f"{CSP_BEGIN}\n"
        f'  <meta http-equiv="Content-Security-Policy" content="{attribute}">\n'
        f"  {CSP_END}"
    )


def inject_csp(page: Path) -> bool:
    """Pin this page's inline scripts and handlers by hash.

    The nginx header keeps 'unsafe-inline' as a fallback for browsers without
    hash support; policies combine restrictively, so supporting browsers accept
    only the hashed inline code and reject injected script. Returns True when the
    page keeps 'unsafe-inline' for attributes because handlers are built at runtime.
    """
    text = page.read_text(encoding="utf-8")
    text = CSP_BLOCK_RE.sub("", text)
    block = csp_block(text)
    text, count = re.subn(
        r"(<head\b[^>]*>)",
        lambda match: match.group(1) + "\n  " + block,
        text,
        count=1,
        flags=re.IGNORECASE,
    )
    if not count:
        raise RuntimeError(f"{page}: no <head> element for the CSP policy")
    page.write_text(text, encoding="utf-8")
    return "script-src-attr 'unsafe-inline'" in block


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: generate_seo.py <frontend_root> <base_url>", file=sys.stderr)
        return 2
    root = Path(sys.argv[1])
    base = sys.argv[2].rstrip("/")

    tools = load_catalog(root)
    if not tools:
        raise RuntimeError(f"no public tools loaded from {root / 'assets' / 'tool-catalog.json'}")
    manifest = load_manifest(root)
    by_slug = {t["slug"]: t for t in tools}

    # Catalog order is the stable sort for related tools; pages that are not on
    # disk never get linked so every href resolves.
    by_category: dict[str, list[dict]] = {}
    for record in tools:
        by_category.setdefault(record.get("category") or "", []).append(record)
    present = {page.parent.name for page in (root / "tools").glob("*/index.html")}
    by_category = {
        category: [record for record in records if record["slug"] in present]
        for category, records in by_category.items()
    }
    published: dict[str, set[str]] = {}
    localized_names: dict[str, dict[str, str]] = {}
    for code, info in sorted(manifest.items()):
        locale_path = (info.get("path") or "") if isinstance(info, dict) else ""
        pages = info.get("pages") if isinstance(info, dict) else {}
        pages = pages if isinstance(pages, dict) else {}
        # Only link a locale copy that is really on disk, so no href 404s.
        slugs = {
            relative.strip("/").split("/")[-1]
            for relative in pages
            if isinstance(relative, str) and relative.startswith("tools/")
            and (root / locale_path / relative / "index.html").is_file()
        }
        published[code] = slugs
        localized_names[code] = {
            slug: (pages.get("tools/" + slug + "/") or {}).get("name") or ""
            for slug in slugs
        }

    home = root / "index.html"
    inject(home, homepage_block(base, hreflang_tags(alternate_block(base, "", manifest))))

    n = 0
    for t in tools:
        page = root / "tools" / t["slug"] / "index.html"
        if page.exists():
            alternates = hreflang_tags(alternate_block(base, "tools/" + t["slug"] + "/", manifest))
            inject(page, tool_block(base, t, alternates))
            name = t.get("name") or t["slug"]
            inject_tool_links(
                page,
                breadcrumb_html(name, "", "en"),
                related_html(related_links(t["slug"], t.get("category") or "", by_category,
                                           set(), {}, ""), "en"),
            )
            n += 1

    # Localized copies were rendered by generate_i18n.py before this pass, so
    # their inline scripts are hashed below exactly like the English pages.
    localized = 0
    for code, info in sorted(manifest.items()):
        locale_path = info.get("path") or ""
        for relative, meta in sorted(info.get("pages", {}).items()):
            page = root / locale_path / relative / "index.html"
            if not page.is_file():
                continue
            alternates = hreflang_tags(alternate_block(base, relative, manifest))
            url = base + "/" + locale_path + "/" + relative
            if relative == "":
                if meta.get("name"):
                    source = page.read_text(encoding="utf-8")
                    source = re.sub(r"<title>.*?</title>", "<title>" + html.escape(meta["name"]) + "</title>",
                                    source, count=1, flags=re.S)
                    page.write_text(source, encoding="utf-8")
                inject(page, homepage_block(base, alternates, meta.get("name") or SITE_NAME,
                                            meta.get("description") or HOME_DESC,
                                            info.get("htmlLang", code), url))
            else:
                slug = relative.strip("/").split("/")[-1]
                record = by_slug.get(slug)
                if not record:
                    continue
                inject(page, tool_block(base, record, alternates, meta.get("name"),
                                        meta.get("description"), url, info.get("htmlLang", code),
                                        meta.get("guidance")))
                name = meta.get("name") or record.get("name") or slug
                inject_tool_links(
                    page,
                    breadcrumb_html(name, locale_path, code),
                    related_html(related_links(slug, record.get("category") or "", by_category,
                                               published.get(code, set()),
                                               localized_names.get(code, {}), locale_path), code),
                )
            localized += 1

    pages = 0
    dynamic = 0
    for page in sorted(root.rglob("*.html")):
        dynamic += inject_csp(page)
        pages += 1

    print(f"Injected SEO into homepage + {n} tool pages (base={base})")
    if localized:
        print(f"Injected localized SEO into {localized} pages across {len(manifest)} locales")
    print(
        f"Injected per-page CSP hashes into {pages} pages "
        f"({dynamic} keep unsafe-inline for runtime-built handlers)"
    )
    return 0


